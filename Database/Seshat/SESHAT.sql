IF OBJECT_ID(N'dbo.SESHAT_REMINDERS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SESHAT_REMINDERS
    (
        ID int IDENTITY(1,1) NOT NULL CONSTRAINT PK_SESHAT_REMINDERS PRIMARY KEY,
        DOCUMENT_ID int NOT NULL,
        KPI_NAME nvarchar(300) NOT NULL,
        NOTIFY_CHANNEL nvarchar(20) NOT NULL,
        EMAIL nvarchar(320) NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_EMAIL DEFAULT N'',
        PHONE_NO nvarchar(50) NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_PHONE_NO DEFAULT N'',
        DAYS_BEFORE int NOT NULL,
        SUBJECT nvarchar(300) NOT NULL,
        BODY nvarchar(max) NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_BODY DEFAULT N'',
        ACTIVE bit NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_ACTIVE DEFAULT 1,
        CREATED_BY nvarchar(256) NOT NULL,
        CREATED_AT datetimeoffset NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_CREATED_AT DEFAULT SYSDATETIMEOFFSET(),
        UPDATED_BY nvarchar(256) NOT NULL,
        UPDATE_TIME datetimeoffset NOT NULL CONSTRAINT DF_SESHAT_REMINDERS_UPDATE_TIME DEFAULT SYSDATETIMEOFFSET(),
        CONSTRAINT FK_SESHAT_REMINDERS_DOCUMENTS FOREIGN KEY (DOCUMENT_ID)
            REFERENCES dbo.SESHAT_DOCUMENTS(ID)
            ON DELETE CASCADE,
        CONSTRAINT CK_SESHAT_REMINDERS_CHANNEL CHECK (NOTIFY_CHANNEL IN (N'EMAIL', N'SMS')),
        CONSTRAINT CK_SESHAT_REMINDERS_CONTACT CHECK ((NOTIFY_CHANNEL = N'EMAIL' AND EMAIL <> N'') OR (NOTIFY_CHANNEL = N'SMS' AND PHONE_NO <> N'')),
        CONSTRAINT CK_SESHAT_REMINDERS_DAYS CHECK (DAYS_BEFORE BETWEEN 1 AND 365)
    );
END;
