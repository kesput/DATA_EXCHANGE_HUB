IF OBJECT_ID(N'dbo.SESHAT_DOCUMENTS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SESHAT_DOCUMENTS
    (
        ID int IDENTITY(1,1) NOT NULL CONSTRAINT PK_SESHAT_DOCUMENTS PRIMARY KEY,
        TITLE nvarchar(200) NOT NULL,
        DESCRIPTION nvarchar(max) NOT NULL,
        KEYWORDS nvarchar(500) NOT NULL CONSTRAINT DF_SESHAT_DOCUMENTS_KEYWORDS DEFAULT N'',
        STATUS nvarchar(30) NOT NULL CONSTRAINT DF_SESHAT_DOCUMENTS_STATUS DEFAULT N'ACTIVE',
        VALID_FROM date NULL,
        VALID_TO date NULL,
        CREATED_BY nvarchar(256) NOT NULL,
        CREATED_AT datetimeoffset NOT NULL CONSTRAINT DF_SESHAT_DOCUMENTS_CREATED_AT DEFAULT SYSDATETIMEOFFSET(),
        UPDATED_BY nvarchar(256) NOT NULL,
        UPDATE_TIME datetimeoffset NOT NULL CONSTRAINT DF_SESHAT_DOCUMENTS_UPDATE_TIME DEFAULT SYSDATETIMEOFFSET(),
        REMINDER_DAYS_BEFORE int NULL
    );
END;

IF OBJECT_ID(N'dbo.SESHAT_DOCUMENT_COUNTRIES', N'U') IS NULL
