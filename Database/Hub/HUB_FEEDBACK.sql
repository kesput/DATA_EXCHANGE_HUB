IF OBJECT_ID(N'BLS_LOGIT_STAT.dbo.HUB_SUGGESTIONS', N'U') IS NULL
BEGIN
    CREATE TABLE [BLS_LOGIT_STAT].[dbo].[HUB_SUGGESTIONS]
    (
        ID int IDENTITY(1,1) NOT NULL CONSTRAINT PK_HUB_SUGGESTIONS PRIMARY KEY,
        USER_NAME nvarchar(256) NOT NULL,
        MESSAGE nvarchar(2000) NOT NULL,
        STATUS nvarchar(30) NOT NULL CONSTRAINT DF_HUB_SUGGESTIONS_STATUS DEFAULT N'NEW',
        CREATED_AT datetimeoffset(7) NOT NULL CONSTRAINT DF_HUB_SUGGESTIONS_CREATED_AT DEFAULT SYSDATETIMEOFFSET(),
        REVIEWED_AT datetimeoffset(7) NULL,
        REVIEWED_BY nvarchar(256) NULL,
        REVIEW_COMMENT nvarchar(1000) NULL,
        CONSTRAINT CK_HUB_SUGGESTIONS_STATUS CHECK (STATUS IN (N'NEW', N'REVIEWED', N'DONE', N'REJECTED'))
    );

    CREATE INDEX IX_HUB_SUGGESTIONS_STATUS
        ON [BLS_LOGIT_STAT].[dbo].[HUB_SUGGESTIONS](STATUS, CREATED_AT DESC);
END;
GO
