IF OBJECT_ID(N'dbo.HUB_SEND_MAIL_LOG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.HUB_SEND_MAIL_LOG
    (
        ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_HUB_SEND_MAIL_LOG PRIMARY KEY,
        APPLICATION_NAME nvarchar(80) NOT NULL,
        PROCESS_NAME nvarchar(160) NOT NULL,
        RECIPIENT_EMAIL nvarchar(320) NOT NULL,
        RECIPIENT_NAME nvarchar(160) NOT NULL CONSTRAINT DF_HUB_SEND_MAIL_LOG_RECIPIENT_NAME DEFAULT N'',
        SUBJECT nvarchar(300) NOT NULL,
        BODY_HTML nvarchar(max) NOT NULL,
        STATUS nvarchar(40) NOT NULL CONSTRAINT DF_HUB_SEND_MAIL_LOG_STATUS DEFAULT N'DRAFT_SAVED',
        ARCHIVE_PATH nvarchar(1000) NOT NULL,
        ERROR_MESSAGE nvarchar(2000) NULL,
        CREATED_BY nvarchar(256) NOT NULL,
        CREATED_AT datetimeoffset NOT NULL CONSTRAINT DF_HUB_SEND_MAIL_LOG_CREATED_AT DEFAULT SYSDATETIMEOFFSET(),
        SENT_AT datetimeoffset NULL
    );
END

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_HUB_SEND_MAIL_LOG_CREATED_AT' AND object_id = OBJECT_ID(N'dbo.HUB_SEND_MAIL_LOG'))
BEGIN
    CREATE INDEX IX_HUB_SEND_MAIL_LOG_CREATED_AT
        ON dbo.HUB_SEND_MAIL_LOG (CREATED_AT DESC, ID DESC);
END

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_HUB_SEND_MAIL_LOG_RECIPIENT' AND object_id = OBJECT_ID(N'dbo.HUB_SEND_MAIL_LOG'))
BEGIN
    CREATE INDEX IX_HUB_SEND_MAIL_LOG_RECIPIENT
        ON dbo.HUB_SEND_MAIL_LOG (RECIPIENT_EMAIL, CREATED_AT DESC);
END
