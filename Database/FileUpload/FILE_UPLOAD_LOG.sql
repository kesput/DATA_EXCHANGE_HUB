IF NOT EXISTS (
    SELECT 1
    FROM sys.tables
    WHERE name = 'FILE_UPLOAD_LOG'
      AND schema_id = SCHEMA_ID('dbo')
)
BEGIN
    CREATE TABLE [BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_LOG] (
        [ID]              BIGINT         IDENTITY(1,1) NOT NULL,
        [ACTION_TYPE]     NVARCHAR(20)   NOT NULL,
        [FILE_NAME]       NVARCHAR(260)  NOT NULL,
        [FILE_PATH]       NVARCHAR(1000) NOT NULL,
        [FILE_SIZE_BYTES] BIGINT         NOT NULL,
        [ACTOR_USER]      NVARCHAR(256)  NOT NULL,
        [EVENT_AT]        DATETIMEOFFSET NOT NULL DEFAULT SYSDATETIMEOFFSET(),
        CONSTRAINT [PK_FILE_UPLOAD_LOG] PRIMARY KEY ([ID])
    );
END

