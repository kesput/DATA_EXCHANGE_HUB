IF NOT EXISTS (
    SELECT 1
    FROM sys.tables
    WHERE name = 'FILE_UPLOAD_NOTIFICATIONS'
      AND schema_id = SCHEMA_ID('dbo')
)
BEGIN
    CREATE TABLE [BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_NOTIFICATIONS] (
        [ID]                INT            IDENTITY(1,1) NOT NULL,
        [ACTOR_USER]        NVARCHAR(256)  NOT NULL,
        [FILE_NAME_PATTERN] NVARCHAR(260)  NOT NULL,
        [TRIGGER_TYPE]      NVARCHAR(20)   NOT NULL,
        [NOTIFY_CHANNEL]    NVARCHAR(20)   NOT NULL,
        [EMAIL]             NVARCHAR(320)  NOT NULL CONSTRAINT [DF_FILE_UPLOAD_NOTIFICATIONS_EMAIL] DEFAULT N'',
        [PHONE_NO]          NVARCHAR(50)   NOT NULL CONSTRAINT [DF_FILE_UPLOAD_NOTIFICATIONS_PHONE_NO] DEFAULT N'',
        [ACTIVE]            BIT            NOT NULL CONSTRAINT [DF_FILE_UPLOAD_NOTIFICATIONS_ACTIVE] DEFAULT 1,
        [CREATED_AT]        DATETIMEOFFSET NOT NULL CONSTRAINT [DF_FILE_UPLOAD_NOTIFICATIONS_CREATED_AT] DEFAULT SYSDATETIMEOFFSET(),
        [UPDATE_TIME]       DATETIMEOFFSET NOT NULL CONSTRAINT [DF_FILE_UPLOAD_NOTIFICATIONS_UPDATE_TIME] DEFAULT SYSDATETIMEOFFSET(),
        CONSTRAINT [PK_FILE_UPLOAD_NOTIFICATIONS] PRIMARY KEY ([ID]),
        CONSTRAINT [CK_FILE_UPLOAD_NOTIFICATIONS_TRIGGER] CHECK ([TRIGGER_TYPE] IN (N'NEW_UPLOAD', N'REPLACE_UPLOAD', N'ANY_UPLOAD')),
        CONSTRAINT [CK_FILE_UPLOAD_NOTIFICATIONS_CHANNEL] CHECK ([NOTIFY_CHANNEL] IN (N'EMAIL', N'SMS')),
        CONSTRAINT [CK_FILE_UPLOAD_NOTIFICATIONS_CONTACT] CHECK (([NOTIFY_CHANNEL] = N'EMAIL' AND [EMAIL] <> N'') OR ([NOTIFY_CHANNEL] = N'SMS' AND [PHONE_NO] <> N''))
    );
END

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'UX_FILE_UPLOAD_NOTIFICATIONS_RULE'
      AND object_id = OBJECT_ID('[BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_NOTIFICATIONS]')
)
BEGIN
    CREATE UNIQUE INDEX [UX_FILE_UPLOAD_NOTIFICATIONS_RULE]
    ON [BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_NOTIFICATIONS] ([ACTOR_USER], [FILE_NAME_PATTERN], [TRIGGER_TYPE], [NOTIFY_CHANNEL]);
END

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE name = 'IX_FILE_UPLOAD_NOTIFICATIONS_ACTIVE'
      AND object_id = OBJECT_ID('[BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_NOTIFICATIONS]')
)
BEGIN
    CREATE INDEX [IX_FILE_UPLOAD_NOTIFICATIONS_ACTIVE]
    ON [BLS_LOGIT_STAT].[dbo].[FILE_UPLOAD_NOTIFICATIONS] ([ACTIVE], [TRIGGER_TYPE], [UPDATE_TIME] DESC);
END
