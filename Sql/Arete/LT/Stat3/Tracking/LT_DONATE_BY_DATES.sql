-- SQL_DESCRIPTION: Paramai perduotu prekiu ataskaita pagal pasirinktas dienas
-- SQL_PARAM_MUST: @SNDATE|date||Pradzios data|format=yyyyMMdd
-- SQL_PARAM_MUST: @ENDATE|date||Pabaigos data|format=yyyyMMdd

SELECT 
	DATVAZ.NDORD
	,LTRIM(RTRIM(ISNULL(OrgAll.OName, VOCORG.ORG))) as ORG
	,BUYERH.FULLNAME as BUYER
	,BUYERH.EMAIL as BUYER_EMAIL
	,DATVAZ.PREFSTOCK 
	,DATVAZ.INF_PREK
	,PRODUCTH.BARCODE
	,PRODUCT.PRODNAME
	,PRODUCT.KORG
	,NORD = RTRIM(VAZTAR.NORD)
	,DATVAZ.AMOUNT as VNT
	,PLL = CASE
		WHEN ISNULL(DATVAZ.AMOUNT,0)=0 THEN '0'	   
	  	WHEN VOCPREK.TLIC='D' THEN '0'
	  	WHEN VOCPREK.TVNT='V' THEN FORMAT(DATVAZ.AMOUNT / (VOCPREK.KIEKD * VOCPREK.KIEKP),'0.###')
		ELSE FORMAT(DATVAZ.AMOUNT / VOCPREK.DNET / VOCPREK.KIEKD / VOCPREK.KIEKP,'0.###')
	  END
	 ,[BRUTTO_KG] = CASE
		 WHEN VOCPREK.TVNT='K' and VOCPREK.TLIC!='D' THEN FORMAT(DATVAZ.AMOUNT / VOCPREK.DNET * VOCPREK.BRUTTO,'0.###')
		 WHEN VOCPREK.TLIC!='D' THEN FORMAT(DATVAZ.AMOUNT * VOCPREK.BRUTTO,'0.###')
		 ELSE '0'
	 END

FROM [SNTXDATA].[dbo].[DATVAZ] as DATVAZ WITH (NOLOCK) 
LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.FIRMID=DATVAZ.FIRMID and VOCPREK.INF_PREK=DATVAZ.INF_PREK 
LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID=DATVAZ.FIRMID and PRODUCT.INF_PREK=DATVAZ.INF_PREK 
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as PRODUCTH WITH (NOLOCK) on PRODUCTH.FIRMID=DATVAZ.FIRMID and PRODUCTH.INF_PREK=DATVAZ.INF_PREK and PRODUCTH.[SID] in ('SNT','LOG')
LEFT JOIN [SNTXDATA].[dbo].[OWNER] as [OWNER] WITH (NOLOCK) on [OWNER].ID=PRODUCT.OWNERID and [OWNER].FIRMID=DATVAZ.FIRMID 
LEFT JOIN [SNTXDATA].[dbo].[VAZTAR] as VAZTAR WITH (NOLOCK) on VAZTAR.FIRMID = DATVAZ.FIRMID AND VAZTAR.PREFSTOCK = DATVAZ.PREFSTOCK AND VAZTAR.NW = DATVAZ.NW 
LEFT JOIN [SNTXDATA].[dbo].[VAZTAR] as VAZTAR2 WITH (NOLOCK) on VAZTAR2.FIRMID = VAZTAR.FIRMID AND VAZTAR2.PREFSTOCK = VAZTAR.PREFSTOCK AND VAZTAR2.NW = VAZTAR.NWMA 
LEFT JOIN [SNTXDATA].[dbo].[VAZTTYPE] as VAZTTYPE WITH (NOLOCK) on VAZTTYPE.VAZTTYPEID=VAZTAR.VAZTTYPEID
LEFT JOIN [SNTXDATA].[dbo].[ORDSTATROW] as ORDSTATROW WITH (NOLOCK, INDEX(PK_ORDSTATROW)) ON ORDSTATROW.ORDSTATID = DATVAZ.ORDSTATID AND ORDSTATROW.NUM = DATVAZ.ORDERLINENO and ORDSTATROW.FIRMID=DATVAZ.FIRMID and ORDSTATROW.PREFSTOCK=DATVAZ.PREFSTOCK
LEFT JOIN [SNTXDATA].dbo.ORDSTAT as ORDSTAT WITH (NOLOCK) on ORDSTAT.ORDSTATID = DATVAZ.ORDSTATID AND NOT(VAZTAR.TCUS = 'W' AND VAZTAR.TORG IN ('Z', 'Q') OR VAZTAR.TORG = 'U' AND VAZTAR.TPRE = 'Z')
LEFT JOIN [SNTXDATA].dbo.ORDHED as ORDHED WITH (NOLOCK) on ORDHED.ORDID = DATVAZ.ORDSTATID AND (VAZTAR.TCUS = 'W' AND VAZTAR.TORG IN ('Z', 'Q') OR VAZTAR.TORG = 'U' AND VAZTAR.TPRE = 'Z')
LEFT JOIN [QLIKDATA].[dbo].[GROUPS] as GROUPS WITH (NOLOCK) on GROUPS.[GROUP_ID]=PRODUCTH.GROUPID 
LEFT LOOP JOIN [SNTXDATA].dbo.VOCORG as VOCORG WITH (NOLOCK) on VOCORG.CODEORG = VAZTAR.CORG AND VOCORG.PREF = DATVAZ.[PREF] AND VOCORG.FIRMID = DATVAZ.FIRMID 
LEFT LOOP JOIN [SNTXDATA].dbo.ORGPOS as ORGPOS WITH (NOLOCK) on ORGPOS.POSID = VOCORG.POSID 
LEFT LOOP JOIN[SNTXDATA].dbo.ORGALL as ORGALL WITH (NOLOCK) on ORGALL.ORGID = ORGPOS.ORGID
LEFT JOIN [QLIKDATA].[dbo].[WAREHOUSE] as WAREHOUSE WITH (NOLOCK) on WAREHOUSE.FIRMID=DATVAZ.FIRMID and WAREHOUSE.WAREHOUSE=VAZTAR.RELPREFSTOCK and WAREHOUSE.[SID]='SNT'
LEFT JOIN [QLIKDATA].dbo.[BUYERH] as BUYERH WITH (NOLOCK) on BUYERH.ID=PRODUCTH.BUYERID and BUYERH.ACTIVE=1 and BUYERH.[SID]='SNT'
WHERE DATVAZ.FIRMID='SA'
and DATVAZ.[PREF] in ('VBL','VBM')
and (DATVAZ.NDORD>=@SNDATE and DATVAZ.NDORD<=@ENDATE)
and VAZTTYPE.OPERTYPE='WRITEOFF'
and VAZTTYPE.OPERDOCDESC in ('Prekių nurašymas')
and VAZTAR.CANC = 'N'
and ([OWNER].SHORTNAME='SNX')
and LTRIM(RTRIM(ISNULL(OrgAll.OName, VOCORG.ORG))) in ('wKOME, Parama-galiojimas')
UNION ALL
SELECT  

      INVOICE.[NDATE]
	  ,INVOICELINE.WRITEOFFDIM+','+INTERNALCUST.CUSTNAME as ORG
	  ,BUYERH.FULLNAME as BUYER
  	  ,BUYERH.EMAIL as BUYER_EMAIL
      ,INVOICE.[INVPREFSTOCK] as PREFSTOCK
	  ,INVOICELINE.INF_PREK
	  ,PRODUCTH.BARCODE
	  ,PRODUCT.PRODNAME
	  ,PRODUCT.KORG
	  ,NORD = INVOICE.INVOICENO
	  ,VNT = CASE WHEN INVOICE.ADJUSTMENTTYPE='ADJUSTMENT_MINUS' THEN ABS(INVOICELINE.QUANTITY)
			 ELSE ABS(INVOICELINE.QUANTITY)*(-1) END
	,PLL = ABS(CASE
		WHEN ISNULL(INVOICELINE.QUANTITY,0)=0 THEN '0'	   
	  	WHEN VOCPREK.TLIC='D' THEN '0'
	  	WHEN VOCPREK.TVNT='V' THEN FORMAT(INVOICELINE.QUANTITY / (VOCPREK.KIEKD * VOCPREK.KIEKP),'0.###')
		ELSE FORMAT(INVOICELINE.QUANTITY / VOCPREK.DNET / VOCPREK.KIEKD / VOCPREK.KIEKP,'0.###')
	  END)
	 ,[BRUTTO_KG] = ABS(CASE
		 WHEN VOCPREK.TVNT='K' and VOCPREK.TLIC!='D' THEN FORMAT(INVOICELINE.QUANTITY / VOCPREK.DNET * VOCPREK.BRUTTO,'0.###')
		 WHEN VOCPREK.TLIC!='D' THEN FORMAT(INVOICELINE.QUANTITY * VOCPREK.BRUTTO,'0.###')
		 ELSE '0'
	 END)
FROM SNTXDATA.dbo.INVOICE as INVOICE WITH (NOLOCK) 
LEFT JOIN SNTXDATA.dbo.INVOICELINE as INVOICELINE WITH (NOLOCK) on INVOICELINE.INVOICEID=INVOICE.INVOICEID
LEFT JOIN SNTXDATA.dbo.INTERNALCUST as INTERNALCUST WITH (NOLOCK) on INTERNALCUST.FIRMID=INVOICE.FIRMID and INTERNALCUST.INTCUSTID = INVOICE.INTERNALCLIID
LEFT JOIN [SNTXDATA].[dbo].[OWNER] as [OWNER] WITH (NOLOCK) on [OWNER].ID=INVOICE.[OWNERID] and [OWNER].FIRMID=INVOICE.FIRMID
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as PRODUCTH WITH (NOLOCK) on PRODUCTH.FIRMID=INVOICE.FIRMID and PRODUCTH.INF_PREK=INVOICELINE.INF_PREK and PRODUCTH.[SID] in ('SNT','LOG')
LEFT JOIN [QLIKDATA].dbo.[BUYERH] as BUYERH WITH (NOLOCK) on BUYERH.ID=PRODUCTH.BUYERID and BUYERH.ACTIVE=1 and BUYERH.[SID]='SNT'
LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID=INVOICE.FIRMID and PRODUCT.INF_PREK=INVOICELINE.INF_PREK 
LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.FIRMID=INVOICE.FIRMID and VOCPREK.INF_PREK=INVOICELINE.INF_PREK
WHERE
INVOICE.FIRMID='SA'
and INVOICE.ACTIVE=1
and INVOICE.CANCELLED=0
and INVOICE.TEST=0
and (INVOICE.NDATE>=@SNDATE and INVOICE.NDATE<=@ENDATE)
and INTERNALCUST.CUSTNAME in ('Vidiniai nurašymai - Parama')
and INVOICE.[INVOICEOWNER]='ATLASLT'
and INVOICE.ADJUSTMENTTYPE='ADJUSTMENT_MINUS'
and ([OWNER].SHORTNAME='SNX');