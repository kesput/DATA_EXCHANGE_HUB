-- SQL_DESCRIPTION: PROMO FORECAST nuo siandienos produkto pjuviu: kiekiai, tinklu skaicius ir akciju laikotarpiai pagal INF_PREK.
-- SQL_FILTER: INF_PREK|KAIROS_PROMO_FORECAST.[INF_PREK]|text|eq,like,in|Vidinis prekes kodas.
-- SQL_FILTER: CLIENT|KAIROS_PROMO_FORECAST.[CLIENT]|text|eq,like,in|Klientas / tinklas.
-- SQL_FILTER: PROMO_START|KAIROS_PROMO_FORECAST.[PROMO_START]|date|eq,gte,lte|Akcijos pradzios data.
-- SQL_FILTER: PROMO_END|KAIROS_PROMO_FORECAST.[PROMO_END]|date|eq,gte,lte|Akcijos pabaigos data.
-- SQL_FILTER: STATUS|KAIROS_PROMO_FORECAST.[STATUS]|text|eq,like,in|PROMO FORECAST statusas.

SELECT
      PRODUCT_PROMO.[INF_PREK]
      ,COUNT_BIG(1) AS PROMO_LINES
      ,COUNT(DISTINCT PRODUCT_PROMO.[CLIENT]) AS CLIENTS_COUNT
      ,STUFF((
            SELECT DISTINCT N', ' + CLIENT_LIST.[CLIENT]
            FROM [BLS_LOGIT_STAT].[dbo].[KAIROS_PROMO_FORECAST] AS CLIENT_LIST WITH (NOLOCK)
            WHERE CLIENT_LIST.[INF_PREK] = PRODUCT_PROMO.[INF_PREK]
              AND CLIENT_LIST.[PROMO_END] >= CAST(GETDATE() AS date)
            FOR XML PATH(''), TYPE
       ).value('.', 'nvarchar(max)'), 1, 2, N'') AS CLIENTS
      ,MIN(CASE
            WHEN PRODUCT_PROMO.[BUY_START] >= CAST(GETDATE() AS date)
            THEN PRODUCT_PROMO.[BUY_START]
       END) AS FIRST_FUTURE_BUY_START
      ,MAX(CASE
            WHEN PRODUCT_PROMO.[BUY_START] >= CAST(GETDATE() AS date)
            THEN PRODUCT_PROMO.[BUY_START]
       END) AS LAST_FUTURE_BUY_START
      ,COUNT(CASE
            WHEN PRODUCT_PROMO.[BUY_START] < CAST(GETDATE() AS date)
             AND PRODUCT_PROMO.[PROMO_END] >= CAST(GETDATE() AS date)
            THEN 1
       END) AS ACTIVE_PAST_BUY_LINES
      ,MIN(CASE
            WHEN PRODUCT_PROMO.[BUY_START] < CAST(GETDATE() AS date)
             AND PRODUCT_PROMO.[PROMO_END] >= CAST(GETDATE() AS date)
            THEN PRODUCT_PROMO.[BUY_START]
       END) AS FIRST_ACTIVE_PAST_BUY_START
      ,MIN(PRODUCT_PROMO.[PROMO_START]) AS FIRST_PROMO_START
      ,MAX(PRODUCT_PROMO.[PROMO_END]) AS LAST_PROMO_END
      ,SUM(ISNULL(PRODUCT_PROMO.[QTY], 0)) AS PLAN_PROMO_QTY
      ,COUNT(DISTINCT PRODUCT_PROMO.[STATUS]) AS STATUS_COUNT
FROM [BLS_LOGIT_STAT].[dbo].[KAIROS_PROMO_FORECAST] AS PRODUCT_PROMO WITH (NOLOCK)
WHERE PRODUCT_PROMO.[PROMO_END] >= CAST(GETDATE() AS date)
/* SQL_PARAM_FILTERS */
GROUP BY
      PRODUCT_PROMO.[INF_PREK]
ORDER BY
      CLIENTS_COUNT DESC
      ,PLAN_PROMO_QTY DESC
      ,PRODUCT_PROMO.[INF_PREK];
