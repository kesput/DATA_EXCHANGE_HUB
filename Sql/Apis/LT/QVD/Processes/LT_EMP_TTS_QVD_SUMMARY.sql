-- SQL_DESCRIPTION: QvdReport.EmpSummary
-- SQL_PARAM_MUST: @SNDATE|date||QvdReport.DateFrom
-- SQL_PARAM_MUST: @ENDATE|date||QvdReport.DateTo
-- QVD_SOURCE: tts|LT_EMP_TTS|{date:yyyy.MM.dd}_EMP_TTS.qvd|@SNDATE|@ENDATE

SELECT
    _QVD_DATE AS NDATE,
    BRANCH,
    WORKER_ID,
    COUNT(*) AS EVENTS,
    COUNT(DISTINCT WORKER_ID) AS WORKERS
FROM tts
GROUP BY _QVD_DATE,WORKER_ID, BRANCH
ORDER BY _QVD_DATE,WORKER_ID, BRANCH;
