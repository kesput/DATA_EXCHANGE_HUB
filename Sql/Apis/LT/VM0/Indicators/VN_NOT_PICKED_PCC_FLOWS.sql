------------------------------------------------------------
-- 0. Išvalom temp lenteles
------------------------------------------------------------
DROP TABLE IF EXISTS #ORDERS_BASE;
DROP TABLE IF EXISTS #PCK_INVOICE_STATUS;

------------------------------------------------------------
-- 1. ESAMAS SELECT -> #ORDERS_BASE
--
-- Čia išlaikom esamą ORDSTATUS_TMP logiką nepakeistą.
------------------------------------------------------------

SELECT
    CASE 
        WHEN ORDSTAT.ORDERDEST = 2 
             AND ORDSTAT.VALID = 0 
             AND ORDSTAT.ORDERSTATUS IN (8,9)
            THEN 'Cancelled in CC'

        WHEN ORDSTAT.ORDERDEST = 2 
             AND ORDSTAT.VALID = 0
            THEN 'Transfered to CC'

        WHEN (
                (
                    ORDSTAT.ORDERSTATUS = 1 
                    AND (
                        ISNULL(ORDSTATROW.LINESTATUS,0) = 0 
                        OR ORDSTATROW.LINESTATUS = 9
                    )
                ) 
                OR ORDSTAT.ORDERSTATUS = 9
             ) 
             OR ORDSTATROW.AMOUNT = 0
            THEN 'NOT SHIPPED'

        WHEN ORDSTAT.ORDERSTATUS = 1 
             AND (
                    LEN(VAZTAR.NKRO) > 1 
                    OR LEN(VAZTAR.NSAD) > 0 
                    OR INVOICE.INVOICENO IS NOT NULL
                 )
             AND (
                    RECEIPTCONFIRMATION.ISSUEDATETIME IS NOT NULL 
                    OR PAJ.INVOICENO IS NOT NULL
                 )
            THEN 'Departed'

        WHEN ORDSTAT.ORDERSTATUS = 1 
             AND (
                    LEN(VAZTAR.NKRO) > 1 
                    OR LEN(VAZTAR.NSAD) > 0 
                    OR INVOICE.INVOICENO IS NOT NULL
                 )
            THEN 'Ready to dispatch'

        WHEN ORDSTAT.ORDERSTATUS = 1 
             AND LEN(ORDSTATROW.PCKORDERNO) > 1 
             AND ISNULL(ORDSTATROW.AMOUNTSHIPPED,0) = 0
            THEN 'NOT SHIPPED'

        WHEN ORDSTAT.ORDERSTATUS = 1 
             AND LEN(ORDSTATROW.PCKORDERNO) > 1 
             AND NOT ISNULL(ORDSTATROW.AMOUNTSHIPPED,0) > 0
            THEN 'Picked waiting document'

        WHEN ORDSTAT.ORDERSTATUS = 1 
             AND ISNULL(ORDSTATROW.AMOUNTSHIPPED,0) > 0
            THEN 'Picked waiting document'

        WHEN ISNULL(
                 ORDSTATROW.PICKINGTASKID,
                 ORDSTATROW.PCKORDERNO
             ) IS NOT NULL
            THEN 'Picking'

        WHEN ISNULL(ORDSTATROW.PCKORDERNO,0) = 0
            THEN 'Suspend in PREKES'

        ELSE 'Picking' 
    END AS ORDSTATUS_TMP,

    ORGPOS.[ADDRESS],
    ORGPOS.POSNAME,
    PREFDESC.PREF AS PREF_TMP,
    ORDSTATTRP.DVAZNEW,
    ORDSTATTRP.TRPGROUP,

    INVOICE.INVOICEDATE,
    INVOICE.ADDTIME AS INVOICE_TIME,
    INVOICE.CARNUMBER,

    ORDSTAT.XMLORDHEADNW,

    PAJ.ADDTIME AS PAJ_TIME,

    DATEDIFF(
        DAY,
        ORDSTATTRP.DVAZNEW,
        ISNULL(INVOICE.INVOICEDATE,GETDATE())
    ) AS DVAZ_DIFF,

    ORGALL.COUNTRY,

    ORDSTAT.CCUSERID,
    ORDSTAT.ORDSOURCE,
    ORDSTAT.ORDSENDERID,
    ORDSTAT.ORDSENDERID AS SENDERID,

    ORDSTAT.ORDSTATID,
    ORDSTAT.REFORDERNUM,
    ORDSTAT.ORDERTYPE,

    ORDSTAT.DATEBEGIN AS ORDER_DATEBEGIN,
    ORDSTAT.SENDTIME AS ORDER_SENDTIME,

    [OWNER].SHORTNAME AS [OWNER],

    ORGPOS.SALETYPE,
    ORDSTAT.POSID,

    ORDSTATROW.PREFSTOCK,
    ORDSTATROW.LINESTATUS,

    ISNULL(
        ORDSTATROW.PICKINGTASKID,
        ORDSTATROW.PCKORDERNO
    ) AS PCKORDERNO,

    ORDSTATROW.PRODUCTID,

    VOCPREK.INF_PREK,
    VOCPREK.TLIC,
    VOCPREK.INF_PAVADL,

    ORDSTATROW.AMOUNTORIG,
    ORDSTATROW.AMOUNT,
    ORDSTATROW.AMOUNTSHIPPED,

    PREFDESC.SYSTEMNAME,
    XMLORDHEAD.WAREHOUSETO,

    CASE 
        WHEN LEN(VAZTAR.RELPREFSTOCK) > 0 
            THEN VAZTAR.RELPREFSTOCK

        WHEN LEN(
            XMLORDHEAD.SHIPTO.value(
                '(ShipTo/WarehouseTo)[1]',
                'nvarchar(max)'
            )
        ) = 3 
            THEN XMLORDHEAD.SHIPTO.value(
                '(ShipTo/WarehouseTo)[1]',
                'nvarchar(max)'
            )

        ELSE VAZTAR.RELPREFSTOCK
    END AS RELPREFSTOCK,

    INVOICE.INVOICEID,
    INVOICE.INVOICENO,

    VAZTAR.NSAD,
    VAZTAR.NKRO,
    VAZTAR.NORD,
    VAZTAR.CANC,
    VAZTAR.NW,

    INVOICELINE.VALIDUNTIL,
    INVOICELINE.QUANTITY,

    RECEIPTCONFIRMATION.RECEIPTID,
    RECEIPTCONFIRMATIONREF.RECEIPTCONFIRMATIONID,
    RECEIPTCONFIRMATION.ISSUEDATETIME,

    CASE
        WHEN VOCPREK.BRUTTO > 0
            THEN VOCPREK.BRUTTO
        ELSE VOCPREK.NETTO
    END AS BRUTTO,

    CASE
        WHEN VOCPREK.TVNT = 'K'
             AND VOCPREK.TLIC != 'D'
            THEN ORDSTATROW.AMOUNTORIG / VOCPREK.DNET * VOCPREK.BRUTTO

        WHEN VOCPREK.TLIC != 'D'
            THEN ORDSTATROW.AMOUNTORIG * VOCPREK.BRUTTO

        ELSE 0
    END AS BRUTTO_KG_ORDERED,

    CASE
        WHEN ISNULL(ORDSTATROW.AMOUNTSHIPPED,0) = 0
            THEN 0

        WHEN VOCPREK.TVNT = 'K'
             AND VOCPREK.TLIC != 'D'
            THEN ORDSTATROW.AMOUNTSHIPPED / VOCPREK.DNET * VOCPREK.BRUTTO

        WHEN VOCPREK.TLIC != 'D'
            THEN ORDSTATROW.AMOUNTSHIPPED * VOCPREK.BRUTTO

        ELSE 0
    END AS BRUTTO_KG_SHIPED,

    CASE 
        WHEN VOCPREK.TLIC = 'D'
            THEN 0

        WHEN VOCPREK.TVNT = 'V'
            THEN ORDSTATROW.AMOUNTORIG / (VOCPREK.KIEKD * VOCPREK.KIEKP)

        ELSE ORDSTATROW.AMOUNTORIG 
             / VOCPREK.DNET 
             / VOCPREK.KIEKD 
             / VOCPREK.KIEKP
    END AS PLL_BY_ORDER,

    CASE 
        WHEN ISNULL(ORDSTATROW.AMOUNTSHIPPED,0) = 0
            THEN 0

        WHEN VOCPREK.TLIC = 'D'
            THEN 0

        WHEN VOCPREK.TVNT = 'V'
            THEN ORDSTATROW.AMOUNTSHIPPED / (VOCPREK.KIEKD * VOCPREK.KIEKP)

        ELSE ORDSTATROW.AMOUNTSHIPPED
             / VOCPREK.DNET
             / VOCPREK.KIEKD
             / VOCPREK.KIEKP
    END AS PLL_BY_SHIPED

INTO #ORDERS_BASE

FROM SNTXDATA.dbo.ORDSTAT AS ORDSTAT WITH (NOLOCK)

LEFT JOIN SNTXDB.dbo.[OWNER] AS [OWNER] WITH (NOLOCK)
    ON [OWNER].ID = ORDSTAT.OWNERID
    AND [OWNER].FIRMID = ORDSTAT.FIRMID

LEFT JOIN SNTXDB.dbo.ORGPOS AS ORGPOS WITH (NOLOCK)
    ON ORGPOS.POSID = ORDSTAT.POSID
    AND ORGPOS.ACTIVE = 1

LEFT JOIN SNTXDB.dbo.ORGALL AS ORGALL WITH (NOLOCK)
    ON ORGALL.ORGID = ORGPOS.ORGID
    AND ORGALL.FIRMID = ORDSTAT.FIRMID

LEFT JOIN SNTXDATA.dbo.ORDSTATROW AS ORDSTATROW WITH (NOLOCK)
    ON ORDSTATROW.ORDSTATID = ORDSTAT.ORDSTATID
    AND ORDSTATROW.FIRMID = ORDSTAT.FIRMID

LEFT JOIN SNTXDB.dbo.VOCPREK AS VOCPREK WITH (NOLOCK)
    ON VOCPREK.PRODUCTID = ORDSTATROW.PRODUCTID
    AND VOCPREK.FIRMID = ORDSTATROW.FIRMID

LEFT JOIN SNTXDATA.dbo.ORDSTATTRP AS ORDSTATTRP WITH (NOLOCK)
    ON ORDSTATTRP.ORDSTATID = ORDSTATROW.ORDSTATID
    AND ORDSTATTRP.TRPGROUP = ORDSTATROW.TRPGROUP

LEFT JOIN SNTXDB.dbo.XMLORDHEAD AS XMLORDHEAD WITH (NOLOCK)
    ON XMLORDHEAD.NW = ORDSTAT.XMLORDHEADNW
    AND XMLORDHEAD.FIRMID = ORDSTAT.FIRMID

LEFT JOIN SNTXDATA.dbo.DATVAZ AS DATVAZ WITH (NOLOCK)
    ON DATVAZ.ORDSTATID = ORDSTATROW.ORDSTATID
    AND DATVAZ.INF_PREK = ORDSTATROW.INF_PREK_X
    AND DATVAZ.FIRMID = ORDSTATROW.FIRMID

LEFT JOIN SNTXDATA.dbo.V_VAZTAR AS VAZTAR WITH (NOLOCK)
    ON VAZTAR.NW = DATVAZ.NW
    AND VAZTAR.FIRMID = DATVAZ.FIRMID
    AND VAZTAR.PREFSTOCK = ORDSTATROW.PREFSTOCK

LEFT JOIN SNTXDB.dbo.PREFDESC AS PREFDESC WITH (NOLOCK)
    ON PREFDESC.FIRMID = XMLORDHEAD.FIRMID
    AND PREFDESC.ACTIVE = 1
    AND PREFDESC.TEST = 0
    AND PREFDESC.PREFSTOCK =
        LEFT(
            ISNULL(
                XMLORDHEAD.WAREHOUSETO,
                VAZTAR.RELPREFSTOCK
            ),
            2
        )

------------------------------------------------------------
-- PAKEISTA INVOICELINE / INVOICE LOGIKA
------------------------------------------------------------

LEFT JOIN SNTXDATA.dbo.INVOICELINE AS INVOICELINE WITH (NOLOCK)
    ON INVOICELINE.ORDSTATID = ORDSTATROW.ORDSTATID
    AND INVOICELINE.PRODUCTID = ORDSTATROW.PRODUCTID
    AND EXISTS (
        SELECT 1
        FROM SNTXDATA.dbo.INVOICE AS INV_CHECK WITH (NOLOCK)
        WHERE INV_CHECK.INVOICEID = INVOICELINE.INVOICEID
          AND INV_CHECK.FIRMID = ORDSTAT.FIRMID
          AND INV_CHECK.TEST = 0
          AND INV_CHECK.ACTIVE = 1
          AND INV_CHECK.VAZTTYPEID NOT IN (24,25,86)
    )

LEFT JOIN SNTXDATA.dbo.INVOICE AS INVOICE WITH (NOLOCK)
    ON INVOICE.INVOICEID = INVOICELINE.INVOICEID
    AND INVOICE.FIRMID = ORDSTAT.FIRMID
    AND INVOICE.TEST = 0
    AND INVOICE.ACTIVE = 1
    AND INVOICE.VAZTTYPEID NOT IN (24,25,86)

------------------------------------------------------------

LEFT JOIN SNTXDATA.dbo.RECEIPTCONFIRMATIONINVOICE AS RECEIPTCONFIRMATIONINVOICE WITH (NOLOCK)
    ON RECEIPTCONFIRMATIONINVOICE.INVOICEID = INVOICE.INVOICEID
    AND RECEIPTCONFIRMATIONINVOICE.FIRMID = INVOICE.FIRMID

LEFT JOIN SNTXDATA.dbo.RECEIPTCONFIRMATION AS RECEIPTCONFIRMATION WITH (NOLOCK)
    ON RECEIPTCONFIRMATION.RECEIPTCONFIRMATIONID =
       RECEIPTCONFIRMATIONINVOICE.RECEIPTCONFIRMATIONID
    AND RECEIPTCONFIRMATION.FIRMID = INVOICE.FIRMID

LEFT JOIN SNTXDATA.dbo.RECEIPTCONFIRMATIONREF AS RECEIPTCONFIRMATIONREF WITH (NOLOCK)
    ON RECEIPTCONFIRMATIONREF.REFERENCEID = ORDSTAT.REFORDERNUM

LEFT JOIN SNTXDATA.dbo.INVOICE AS PAJ WITH (NOLOCK)
    ON PAJ.INVOICENO = INVOICE.INVOICENO
    AND (
        (
            PAJ.INVOICEOWNER = 'PCCLT'
            AND PAJ.OPERTYPE IN ('Internal','Movement')
            AND PAJ.VAZTTYPEID IN (24,25,26,29,42,51)
        )
        OR
        (
            PAJ.FIRMID IN ('LV','EE')
            AND PAJ.INVOICEOWNER IN ('PCCLV_PROD','PCCEE')
            AND PAJ.OPERTYPE = 'Purchase'
            AND PAJ.VAZTTYPEID = '32'
        )
    )

WHERE
    ORGPOS.ORGID IN (47,30452,2002034)
    AND ORDSTAT.ORDSENDERID IN ('TLT','SNL','ILT','SNX','SNP')
    AND VOCPREK.TLIC NOT IN ('D','Z')
    AND ORDSTATTRP.DVAZNEW >= DATEADD(DAY,-20,GETDATE())
    AND ISNULL(ORDSTAT.ONETIMECUSTOMER,0) <> 1
--  AND ORGALL.COUNTRY = 'EST'
    AND LEFT(ORDSTATROW.PREFSTOCK,2) = 'VN'
--    AND INVOICE.SUBOPERTYPE <> 'CREDITNOTE'
--  AND ORDSTAT.ORDSTATID = 50609743;


------------------------------------------------------------
-- 2. Randame tik tuos PCKORDERNO:
--
--    a) kuriuose yra bent viena Picking eilutė
--    b) ir tam pačiam PCKORDERNO bent viena kita eilutė
--       jau turi INVOICEID
--
-- Gaunam po VIENĄ įrašą PCKORDERNO.
------------------------------------------------------------

SELECT DISTINCT
    P.PCKORDERNO,
    HAS_INVOICE = 1
INTO #PCK_INVOICE_STATUS
FROM
(
    SELECT DISTINCT
        PCKORDERNO
    FROM #ORDERS_BASE
    WHERE ORDSTATUS_TMP = 'Picking'
      AND PCKORDERNO IS NOT NULL
) AS P

INNER JOIN #ORDERS_BASE AS I
    ON I.PCKORDERNO = P.PCKORDERNO
    AND I.INVOICEID IS NOT NULL;


------------------------------------------------------------
-- Galima indeksuoti jungimo raktą
------------------------------------------------------------

CREATE UNIQUE CLUSTERED INDEX IX_PCK_INVOICE_STATUS
    ON #PCK_INVOICE_STATUS(PCKORDERNO);


------------------------------------------------------------
-- 3. Galutinis rezultatas
--
-- ORDSTATUS_TMP = originalus statusas
-- ORDER_STATUS  = galutinė dimensija
------------------------------------------------------------

SELECT
    CASE
        WHEN B.ORDSTATUS_TMP = 'Picking'
             AND P.HAS_INVOICE = 1
             AND B.INVOICEID IS NULL
            THEN 'NOT SHIPPED'
        ELSE B.ORDSTATUS_TMP
    END AS ORDER_STATUS,
    B.*

FROM #ORDERS_BASE AS B

LEFT JOIN #PCK_INVOICE_STATUS AS P
    ON P.PCKORDERNO = B.PCKORDERNO

WHERE
    B.INVOICEID IS NULL
    AND NOT ISNULL(B.PREF_TMP,'EXP') IN ('VBL','VBM')
    AND CASE
            WHEN B.ORDSTATUS_TMP = 'Picking'
                 AND P.HAS_INVOICE = 1
                 AND B.INVOICEID IS NULL
                THEN 'NOT SHIPPED'
            ELSE B.ORDSTATUS_TMP
        END <> 'NOT SHIPPED'

ORDER BY
    B.DVAZNEW,
    B.REFORDERNUM;


------------------------------------------------------------
-- 4. Cleanup
------------------------------------------------------------

DROP TABLE IF EXISTS #PCK_INVOICE_STATUS;
DROP TABLE IF EXISTS #ORDERS_BASE;