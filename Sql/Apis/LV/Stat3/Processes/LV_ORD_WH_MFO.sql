SET DATEFIRST 1;

SELECT
      ORDSTAT.[FIRMID]
     ,ORDSTAT.[REFORDERNUM]
     ,CONVERT(date, ORDSTATTRP.DVAZNEW) AS [Delivery]
     ,ORDSTAT.[POSID] AS [Posid]
     ,ORGALL.ONAME AS [Client]
     ,[ADDRESS] = CASE WHEN ORDSTAT.ONETIMECUSTOMER = 1 THEN COALESCE(NULLIF(SHIPXML.ShipToAddress, ''), ORGPOS.ADDRESS)
                       ELSE ORGPOS.ADDRESS
                       END
     ,BOX = SUM(CAST(ROUND(ORDSTATROW.AMOUNT / VOCPREK.KIEKD, 2) AS FLOAT))
     ,ORGALL.COUNTRY
     ,ORDSTATROW.PREFSTOCK AS [WH]
     ,PLL = CAST(ROUND((CASE
                            WHEN VOCPREK.TVNT = 'V' THEN SUM(CAST(ORDSTATROW.AMOUNT / (VOCPREK.KIEKD * VOCPREK.KIEKP) AS FLOAT)) * 0.95
                            WHEN VOCPREK.TVNT = 'K' THEN SUM(CAST(ORDSTATROW.AMOUNT / ((CASE WHEN VOCPREK.DNET = 0 THEN 1 ELSE VOCPREK.DNET END) * VOCPREK.KIEKD * VOCPREK.KIEKP) AS FLOAT)) * 0.95
                        END ) *
						CASE WHEN ORDSTATROW.PREFSTOCK = 'NF1' THEN 1.3
							 ELSE 1
                        END
                ,3) AS DECIMAL(18,3))
     ,'' AS Rules
     ,'' AS [PICK NUMBER]
     ,'' AS [Planed loading time]
     ,'' AS POD
     ,'' AS [COUNT of actual pallet]
     ,'' AS Problems

FROM [SNTXDATA].[dbo].[ORDSTAT] AS ORDSTAT WITH (NOLOCK)
JOIN [SNTXDATA].[dbo].[ORDSTATROW] AS ORDSTATROW  WITH (NOLOCK) ON ORDSTATROW.ORDSTATID = ORDSTAT.ORDSTATID
JOIN [SNTXDATA].[dbo].[VOCPREK] AS VOCPREK  WITH (NOLOCK) ON VOCPREK.PRODUCTID = ORDSTATROW.PRODUCTID
JOIN [SNTXDATA].[dbo].[ORGPOS] AS ORGPOS WITH (NOLOCK) ON ORGPOS.POSID = ORDSTAT.POSID
JOIN [SNTXDATA].[dbo].[ORGALL] AS ORGALL WITH (NOLOCK) ON ORGALL.ORGID = ORGPOS.ORGID
LEFT JOIN [SNTXDATA].[dbo].[ORDSTATTRP] AS ORDSTATTRP WITH (NOLOCK) ON ORDSTATTRP.ORDSTATID = ORDSTAT.ORDSTATID
OUTER APPLY
    (SELECT
          ShipToXml = CASE WHEN ORDSTAT.ONETIMECUSTOMER = 1 THEN TRY_CAST(ORDSTAT.SHIPTO AS XML)
                           ELSE NULL
                           END
    ) AS XMLDATA
OUTER APPLY
    (SELECT
          ShipToAddress = XMLDATA.ShipToXml.value('(/ShipTo/ShipToAddress/text())[1]', 'nvarchar(255)')
    ) AS SHIPXML

WHERE ORDSTAT.FIRMID = 'LV'
  AND ORDSTAT.OWNERID = '885'
  AND ORDSTATROW.PREFSTOCK NOT LIKE 'JR%'
  AND ((DATEPART(WEEKDAY, CAST(GETDATE() AS date)) = 5
            AND CAST(ORDSTATTRP.DVAZNEW AS date) IN (DATEADD(day, 1, CAST(GETDATE() AS date)), DATEADD(day, 2, CAST(GETDATE() AS date)), DATEADD(day, 3, CAST(GETDATE() AS date))))
			OR (DATEPART(WEEKDAY, CAST(GETDATE() AS date)) <> 5 AND CAST(ORDSTATTRP.DVAZNEW AS date) = DATEADD(day, 1, CAST(GETDATE() AS date)))
      )

GROUP BY
      ORDSTAT.DORD
     ,ORDSTATTRP.DVAZ
     ,ORDSTATTRP.DVAZNEW
     ,ORDSTAT.REFORDERNUM
     ,ORGALL.ONAME
     ,ORGPOS.ADDRESS
     ,ORGALL.COUNTRY
     ,ORDSTATROW.PREFSTOCK
     ,ORDSTAT.POSID
     ,ORDSTAT.[FIRMID]
     ,ORDSTAT.ONETIMECUSTOMER
     ,SHIPXML.ShipToAddress
     ,VOCPREK.TVNT

ORDER BY
      ORDSTATTRP.DVAZNEW
     ,ORDSTAT.REFORDERNUM;