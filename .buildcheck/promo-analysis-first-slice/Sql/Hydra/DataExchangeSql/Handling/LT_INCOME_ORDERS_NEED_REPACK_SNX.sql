;WITH cte AS
(
    SELECT  
          ORDHED.[ORDCODE]
        , ORDHED.[OWNERID]
        , [OWNER].SHORTNAME
        , ORDHED.[PREFSTOCK]
        , ORDDET.PRODUCTID
        , ORDDET.INF_PREK
        , ORDDET.BARCODE
        , PRODUCT.PRODNAME
        , ORDHED.[SENDTIME]
        , ORDHED.[DELIVERYTIME]
        , ORDHED.[ARRIVALTIME]
        , ORDDET.ORDAMOUNT

        , Time_hh_UNIT =
            CASE
              WHEN TRY_CONVERT(decimal(18,12), REPLACE(LABELING_UNIT.OUTPUT_QTY_PER_HOUR, ',', '.')) > 0
                   AND VOCPREK.TVNT='K'
                THEN ORDDET.ORDAMOUNT / NULLIF(VOCPREK.DNET, 0)
                     / NULLIF(TRY_CONVERT(decimal(18,12), REPLACE(LABELING_UNIT.OUTPUT_QTY_PER_HOUR, ',', '.')), 0)
              WHEN TRY_CONVERT(decimal(18,12), REPLACE(LABELING_UNIT.OUTPUT_QTY_PER_HOUR, ',', '.')) > 0
                THEN ORDDET.ORDAMOUNT
                     / NULLIF(TRY_CONVERT(decimal(18,12), REPLACE(LABELING_UNIT.OUTPUT_QTY_PER_HOUR, ',', '.')), 0)
              ELSE 0
            END

        , Time_hh_BOX =
            CASE 
              WHEN LABELING_BOX.OUTPUT_QTY_PER_HOUR IS NOT NULL
                THEN ORDDET.ORDAMOUNT / NULLIF(VOCPREK.KIEKD, 0)
                     / NULLIF(TRY_CONVERT(decimal(18,12), REPLACE(LABELING_BOX.OUTPUT_QTY_PER_HOUR, ',', '.')), 0)
              ELSE 0
            END

        , Time_hh_MBOX =
            CASE 
              WHEN LABELING_MBOX.OUTPUT_QTY_PER_HOUR IS NOT NULL
                THEN ORDDET.ORDAMOUNT / NULLIF(VOCPREK.KIEKM, 0)
                     / NULLIF(TRY_CONVERT(decimal(18,12), REPLACE(LABELING_MBOX.OUTPUT_QTY_PER_HOUR, ',', '.')), 0)
              ELSE 0
            END

        , Time_hh_ITEMCNT =
            CASE 
              WHEN LABELING_ITEMCNT.OUTPUT_QTY_PER_HOUR IS NOT NULL
                THEN ORDDET.ORDAMOUNT / NULLIF(PRODUCT.ITEMCNT, 0)
                     / NULLIF(TRY_CONVERT(decimal(18,12), REPLACE(LABELING_ITEMCNT.OUTPUT_QTY_PER_HOUR, ',', '.')), 0)
              ELSE 0
            END

    FROM [SQL-SQLSTA3-PRD].[SNTXDATA].[dbo].[ORDHED] as ORDHED WITH (NOLOCK)
    LEFT JOIN [SQL-SQLSTA3-PRD].[SNTXDATA].[dbo].[OWNER] as [OWNER] WITH (NOLOCK)
           ON [OWNER].FIRMID=ORDHED.FIRMID and [OWNER].ID=ORDHED.OWNERID and [OWNER].ACTIVE=1
    LEFT JOIN [SQL-SQLSTA3-PRD].[SNTXDATA].[dbo].[ORDDET] as ORDDET WITH (NOLOCK)
           ON ORDDET.ORDID=ORDHED.ORDID and ORDDET.ACTIVE=1
    LEFT JOIN [SQL-SQLSTA3-PRD].[SNTXDATA].[dbo].PRODUCT as PRODUCT WITH (NOLOCK)
           ON PRODUCT.FIRMID=ORDHED.FIRMID and PRODUCT.INF_PREK=ORDDET.INF_PREK
    LEFT JOIN [SQL-SQLSTA3-PRD].[SNTXDATA].[dbo].VOCPREK as VOCPREK WITH (NOLOCK)
           ON VOCPREK.FIRMID=ORDHED.FIRMID and VOCPREK.INF_PREK=ORDDET.INF_PREK

    LEFT JOIN [BLS_LOGIT_STAT].[dbo].[LABELING_PRICELIST] as LABELING_UNIT WITH (NOLOCK)
           ON LABELING_UNIT.FIRMID=[OWNER].FIRMID and LABELING_UNIT.INF_PREK=PRODUCT.INF_PREK
          and LABELING_UNIT.MEASURE='UNIT' and LABELING_UNIT.DATE_FROM = DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)
    LEFT JOIN [BLS_LOGIT_STAT].[dbo].[LABELING_PRICELIST] as LABELING_BOX WITH (NOLOCK)
           ON LABELING_BOX.FIRMID=[OWNER].FIRMID and LABELING_BOX.INF_PREK=PRODUCT.INF_PREK
          and LABELING_BOX.MEASURE='BOX' and LABELING_BOX.DATE_FROM = DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)
    LEFT JOIN [BLS_LOGIT_STAT].[dbo].[LABELING_PRICELIST] as LABELING_MBOX WITH (NOLOCK)
           ON LABELING_MBOX.FIRMID=[OWNER].FIRMID and LABELING_MBOX.INF_PREK=PRODUCT.INF_PREK
          and LABELING_MBOX.MEASURE='MBOX' and LABELING_MBOX.DATE_FROM = DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)
    LEFT JOIN [BLS_LOGIT_STAT].[dbo].[LABELING_PRICELIST] as LABELING_ITEMCNT WITH (NOLOCK)
           ON LABELING_ITEMCNT.FIRMID=[OWNER].FIRMID and LABELING_ITEMCNT.INF_PREK=PRODUCT.INF_PREK
          and LABELING_ITEMCNT.MEASURE='ITEMCNT' and LABELING_ITEMCNT.DATE_FROM = DATEFROMPARTS(YEAR(GETDATE()), MONTH(GETDATE()), 1)

    WHERE ORDHED.FIRMID='SA'
      and ORDHED.PREF in ('VBL','VBM')
      and ORDHED.ACTIVE=1
      and ORDHED.OWNERID=3
      and ORDHED.DELIVERYTIME>=GETDATE()
      and ORDHED.STATE not in (3,9)
      and PRODUCT.REPACK=1
)
SELECT
      *
    , Time_hh_TOTAL =
        COALESCE(Time_hh_UNIT,0)
      + COALESCE(Time_hh_BOX,0)
      + COALESCE(Time_hh_MBOX,0)
      + COALESCE(Time_hh_ITEMCNT,0)
FROM cte
ORDER BY DELIVERYTIME;

