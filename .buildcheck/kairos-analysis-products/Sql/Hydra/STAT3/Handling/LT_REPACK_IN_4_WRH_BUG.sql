-- HYDRA_FILTER: PREFSTOCK | b.PREFSTOCK | text | =,like,in
-- HYDRA_FILTER: OWNER | o.SHORTNAME | text | =,like,in

WITH base AS (
    SELECT
        s.FIRMID,
        s.PREFSTOCK,
        s.PRODUCTID,
        s.INF_PREK,
        s.STOCK
    FROM SNTXDATA.dbo.STOCK s
LEFT JOIN [SNTXDATA].[dbo].[PREFDESC] as p on p.FIRMID=s.FIRMID AND p.PREFMAIN=s.PREFMAIN AND p.ACTIVE=1 AND p.PREFSTOCK=LEFT(s.PREFSTOCK,2)
WHERE s.FIRMID = 'SA'
      AND RIGHT(s.PREFSTOCK,1) = '4'
      AND s.STOCK > 0
	  AND p.PREF in ('VBM','VBL')
	  and not LEFT(s.INF_PREK,4) in ('BELP','BRTT','BRPP','BLPL')
),
labels AS (
    SELECT
        b.PRODUCTID,
        UNIT_STICKER_COMMENT = NULLIF(LTRIM(RTRIM(MAX(CASE WHEN l.ACTIVE = 1 THEN l.COMMENT END))), ''),
        MBOX_STICKER_COMMENT = NULLIF(LTRIM(RTRIM(MAX(CASE WHEN lu.ACTIVE = 1 AND lu.UNITTYPE = 2 THEN lu.COMMENT END))), ''),
        BOX_STICKER_COMMENT =  NULLIF(LTRIM(RTRIM(MAX(CASE WHEN lu.ACTIVE = 1 AND lu.UNITTYPE = 3 THEN lu.COMMENT END))), ''),
        PALLET_STICKER_COMMENT = NULLIF(LTRIM(RTRIM(MAX(CASE WHEN lu.ACTIVE = 1 AND lu.UNITTYPE = 4 THEN lu.COMMENT END))), ''),
        ITEMCNT_STICKER_COMMENT = NULLIF(LTRIM(RTRIM(MAX(CASE WHEN lu.ACTIVE = 1 AND lu.UNITTYPE = 5 THEN lu.COMMENT END))), '')
    FROM base b
    LEFT JOIN WM0.SNTXDB.dbo.PRODLABELN l WITH (NOLOCK) ON l.PRODUCTID = b.PRODUCTID AND l.ACTIVE = 1
    LEFT JOIN WM0.SNTXDB.dbo.PRODLABELUNIT lu WITH (NOLOCK) ON lu.PRODUCTID = b.PRODUCTID AND lu.ACTIVE = 1
    GROUP BY
        b.PRODUCTID
)
SELECT

    b.PREFSTOCK,
    b.PRODUCTID,
    b.INF_PREK,
	p.BARCODE,
	p.PRODNAMELT,
    b.STOCK,
	ISNULL(bu.FULLNAME,m.FULLNAME) as BUYER_NAME,
	ISNULL(bu.EMAIL,m.EMAIL) as EMAIL,
    lab.UNIT_STICKER_COMMENT,
    lab.MBOX_STICKER_COMMENT,
    lab.BOX_STICKER_COMMENT,
    lab.PALLET_STICKER_COMMENT,
    lab.ITEMCNT_STICKER_COMMENT

FROM base b
LEFT JOIN labels lab  ON lab.PRODUCTID = b.PRODUCTID
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as p on p.FIRMID=b.FIRMID and p.INF_PREK=b.INF_PREK and p.ACTIVE=1 AND p.[SID] in ('SNT','LOG')
LEFT JOIN [QLIKDATA].[dbo].[BUYERH] as bu on bu.[SID]=p.[SID] and bu.ID=p.BUYERID and bu.ACTIVE=1
LEFT JOIN [WM0].[SNTXDB].[dbo].[OWNER] as o on o.ID=p.OWNERID and o.FIRMID=p.FIRMID and o.[SID] in ('SNT','BLT') and o.ACTIVE=1
LEFT JOIN [WM0].SNTXECOM.dbo.MANAGER as m on m.ID=o.MANAGERID  and m.ACTIVE=1
WHERE
not p.TLIC in ('Z','D')
AND  (lab.UNIT_STICKER_COMMENT = '(NEKLIJUOJAM)'
   OR (
        lab.UNIT_STICKER_COMMENT IS NULL
    AND lab.MBOX_STICKER_COMMENT IS NULL
    AND lab.BOX_STICKER_COMMENT IS NULL
    AND lab.PALLET_STICKER_COMMENT IS NULL
    AND lab.ITEMCNT_STICKER_COMMENT IS NULL
   ))
   

