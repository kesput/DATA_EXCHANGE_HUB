SELECT 
--	pr.PRODUCTID

	 own.SHORTNAME as [OWNER]
	,GROUPS.GROUP_NAME1
	,GROUPS.GROUP_NAME2
	,GROUPS.GROUP_NAME3
	,GROUPS.GROUP_NAME4
	,GROUPS.GROUP_NAME5
	,pr.INF_PREK
	,PRODUCTH.PRODNAMELT
--	,pr.UNITTYPE
	,pr.LABELLING_TYPE
	,pr.COMMENT
	,REPLACE(REPLACE(REPLACE(UPPER(pr.STICKER),'BANDEROLE','BANDEROLĖ'),'BANDEROLES','BANDEROLĖ'),'BANDEROLĖS','BANDEROLĖ') as STICKER_VBX
	,PRODUCTH.KORG
	,ISNULL(DEPOSITE.DEPOSITE_Y_N,'N') as DEPOSITE_Y_N
--	,VOCPREK.TLICSUBTYPE
	,PRODUCTH.BRUTTO
	,PRODUCTH.KIEKP
	,PRODUCTH.KIEKD
	,PRODUCTH.KIEKM
	,PRODUCTH.ITEMCNT
	,PRODUCTH.DNET
	,PRODUCTH.TLIC
	,PRODUCTH.TNET

	,PRODUCTH.BRANDID
	,PRODUCTH.BRANDDIM
	,PRODUCTH.STORTMP1
--	,PRODUCTH.OWNERID
--	,GROUPID = CASE WHEN PRODUCTH.[SID]='LOG' and not ISNULL(PRODUCTH_BL.GROUPID,0)=0 THEN PRODUCTH_BL.GROUPID
--					ELSE PRODUCTH.GROUPID
--				END
	,LABELLING_TYPE_BRUTTO = CASE WHEN pr.UNITTYPE=1 THEN PRODUCTH.BRUTTO
								  WHEN pr.UNITTYPE=2 THEN ph.BRUTOM
								  WHEN pr.UNITTYPE=3 THEN ph.BRUTOD
								  WHEN pr.UNITTYPE=4 THEN ph.BRUTOP
								  ELSE PRODUCTH.BRUTTO
							 END
FROM
(SELECT DISTINCT
	l.PRODUCTID
	,p.INF_PREK
	,l.LABELID
	,l.LANGLABEL
	,lu.UNITTYPE
	--,p.BRUTTO
	,LABELLING_TYPE = CASE WHEN lu.UNITTYPE=2 THEN 'MBOX'
	      WHEN lu.UNITTYPE=3 THEN 'BOX'
		  WHEN lu.UNITTYPE=4 THEN 'PALLET'
		  WHEN lu.UNITTYPE=5 THEN 'ITEMCNT'
	END
	,COMMENT = CASE WHEN LTRIM(lu.[COMMENT]) like '%#%' THEN SUBSTRING(lu.[COMMENT], 0, CHARINDEX('#', lu.[COMMENT])) ELSE LTRIM(lu.[COMMENT]) END
	,STICKER = CASE WHEN LTRIM(lu.[COMMENT]) like '%#%' THEN LTRIM(SUBSTRING(lu.[COMMENT], 0, CHARINDEX('#', lu.[COMMENT])))
					WHEN LTRIM(lu.[COMMENT]) like '%(%' THEN LTRIM(SUBSTRING(lu.[COMMENT], 0, CHARINDEX('(', lu.[COMMENT]))) 	
					WHEN LTRIM(lu.[COMMENT]) like '% %' THEN LTRIM(SUBSTRING(LTRIM(lu.[COMMENT]), 0, CHARINDEX(' ', LTRIM(lu.[COMMENT]))))
					ELSE LTRIM(lu.[COMMENT]) END

					
FROM [WM0].[SNTXDB].[dbo].[PRODLABELN] as l WITH (NOLOCK)
LEFT JOIN [WM0].[SNTXDB].[dbo].[PRODLABELUNIT] as lu WITH (NOLOCK) on lu.PRODUCTID=l.PRODUCTID and LEN(lu.[COMMENT])>1
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as p WITH (NOLOCK) on p.PRODUCTID=l.PRODUCTID
WHERE p.FIRMID='SA' and LEN(CASE WHEN lu.[COMMENT] like '%#%' THEN SUBSTRING(lu.[COMMENT], 0, CHARINDEX('#', lu.[COMMENT]))	ELSE lu.[COMMENT] END)>1
UNION
SELECT DISTINCT 
		 u.PRODUCTID 
		 ,pp.INF_PREK
		 ,u.LABELID
		 ,u.LANGLABEL
		 ,1 as UNITTYPE
		 ,'UNIT' as LABELLING_TYPE
		,COMMENT = CASE WHEN LTRIM(u.[COMMENT]) like '%#%' THEN SUBSTRING(u.[COMMENT], 0, CHARINDEX('#', u.[COMMENT])) ELSE LTRIM(u.[COMMENT]) END
		,STICKER = CASE WHEN LTRIM(u.[COMMENT]) like '%#%' THEN LTRIM(SUBSTRING(REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ',''), 0, CHARINDEX('#', REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ',''))))
						WHEN LTRIM(u.[COMMENT]) like '%(%' THEN LTRIM(SUBSTRING(REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ',''), 0, CHARINDEX('(', REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ','')))) 	
						WHEN REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ','') like '% %' THEN LTRIM(SUBSTRING(LTRIM(REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ','')), 0, CHARINDEX(' ', LTRIM(REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ','')))))
						ELSE LTRIM(REPLACE(REPLACE(LTRIM(u.[COMMENT]),'[KLASIFIKAVIMAS]_',''),'[KLASIFIKAVIMAS] ','')) END

FROM [WM0].[SNTXDB].[dbo].[PRODLABELN] as u WITH (NOLOCK) 
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as pp WITH (NOLOCK) on pp.PRODUCTID=u.PRODUCTID
WHERE pp.FIRMID='SA' and LEN(CASE WHEN u.[COMMENT] like '%#%' THEN SUBSTRING(u.[COMMENT], 0, CHARINDEX('#', u.[COMMENT])) ELSE u.[COMMENT] END)>1
UNION
SELECT DISTINCT 
		 uu.PRODUCTID 
		 ,pu.INF_PREK
		 ,uu.LABELID
		 ,uu.LANGLABEL
		 ,1 as UNITTYPE
		 ,'BRUTTO' as LABELLING_TYPE
		 ,COMMENT = CASE WHEN uu.[COMMENT] like '%#%' THEN SUBSTRING(uu.[COMMENT], 0, CHARINDEX('#', uu.[COMMENT])) ELSE uu.[COMMENT] END 
		 ,'[KLASIFIKAVIMAS]' as STICKER

FROM [WM0].[SNTXDB].[dbo].[PRODLABELN] as uu WITH (NOLOCK) 
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as pu WITH (NOLOCK) on pu.PRODUCTID=uu.PRODUCTID
WHERE pu.FIRMID='SA' and uu.[COMMENT] like '%KLASIFIKAVIMAS%'
) as pr
LEFT JOIN [QLIKDATA].[dbo].[PRODUCTH] as PRODUCTH WITH (NOLOCK) on PRODUCTH.PRODUCTID=pr.PRODUCTID and PRODUCTH.FIRMID='SA'
LEFT JOIN [QLIKBLS].[dbo].[PRODUCTH] as PRODUCTH_BL WITH (NOLOCK) on PRODUCTH_BL.PRODUCTID=pr.PRODUCTID and PRODUCTH_BL.FIRMID='BL'
LEFT JOIN  QLIKDATA.dbo.GROUPS as GROUPS WITH (NOLOCK) on GROUPS.GROUP_ID=CASE WHEN PRODUCTH.[SID]='LOG' and not ISNULL(PRODUCTH_BL.GROUPID,0)=0 THEN PRODUCTH_BL.GROUPID ELSE PRODUCTH.GROUPID	END
LEFT JOIN [WM0].[SNTXDB].[dbo].[PRODUCT] as ph WITH (NOLOCK) on ph.PRODUCTID=pr.PRODUCTID and ph.FIRMID='SA'
LEFT JOIN [SNTXDATA].[dbo].[OWNER] as own WITH (NOLOCK) on own.ID=PRODUCTH.OWNERID and own.FIRMID=PRODUCTH.FIRMID
LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.PRODUCTID=PRODUCTH.PRODUCTID and VOCPREK.FIRMID=PRODUCTH.FIRMID
LEFT JOIN (SELECT 
		
       VOCPREK.[FIRMID]
	  ,VOCPREK.PREKUNI
	  ,'Y' as DEPOSITE_Y_N

  FROM [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK)
  LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as TARA WITH (NOLOCK) on TARA.FIRMID=VOCPREK.FIRMID and TARA.PRODUCTID=VOCPREK.TARAPRODUCTID
  WHERE VOCPREK.FIRMID='SA' and TARA.TLIC in ('X')
) as DEPOSITE on DEPOSITE.PREKUNI=pr.INF_PREK 
WHERE  
PRODUCTH.[SID] in ('SNT','LOG')
