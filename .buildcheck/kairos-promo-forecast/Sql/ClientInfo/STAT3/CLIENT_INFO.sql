-- HYDRA_FILTER_MUST: FIRMID | ORGALL.[FIRMID] | text | =,in
-- HYDRA_FILTER: COUNTRY | ORGALL.[COUNTRY] | text | =,like,in
-- HYDRA_FILTER: ORGID | ORGALL.[ORGID] | number | =,in
-- HYDRA_FILTER: REGCODE | ORGALL.[REGCODE] | text | =,in
-- HYDRA_FILTER: ONAME | ORGALL.[ONAME] | text | =,like,in
-- HYDRA_FILTER: CORESONDATION_ADDRESS | ORGALL.[ADDRESS] | text | =,like,in
-- HYDRA_FILTER: POSID | ORGPOS.[POSID] | number | =,in
-- HYDRA_FILTER: ADDRESS | ORGPOS.[ADDRESS] | text | =,like,in

SELECT
    ORGALL.[FIRMID],
    ORGALL.[COUNTRY],
    ORGALL.[ORGID],
    ORGALL.[REGCODE],
    ORGALL.[ONAME],
    ORGALL.[ADDRESS] AS CORESONDATION_ADDRESS,
    ORGPOS.[POSID],
    ORGPOS.[ADDRESS]
FROM [SNTXDATA].[dbo].[ORGALL] AS ORGALL
LEFT JOIN [SNTXDATA].[dbo].[ORGPOS] AS ORGPOS
    ON ORGPOS.[ACTIVE] = 1
   AND ORGPOS.[ORGID] = ORGALL.[ORGID]
WHERE ORGALL.[ACTIVE] = 1
  AND ORGPOS.[POSID] IS NOT NULL
