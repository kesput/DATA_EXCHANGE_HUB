-- SQL_DESCRIPTION: Produktu WBX informacija
-- SQL_PARAM_MUST: @FIRMID|text||SA LV ar EE, LIKE fragmentas arba IN sarasas per kableli.|regex=^[A-Za-z0-9_, %_-]+$;message=@FIRMID gali tureti raides, skaicius, kablelius, tarpus, %, _ arba minusus.;operators==,like,in
-- SQL_PARAM: OWNER|text||Filtravimas pagal savininkus.|operators==,like,in;expr=own.SHORTNAME
-- SQL_PARAM: INF_PREK|text||Filtravimas pagal prekes koda.|operators==,like,in;expr=PRODUCTH.INF_PREK
-- SQL_PARAM: BARCODE|text||Filtravimas prekes barkoda.|operators==,like,in;expr=PRODUCTH.BARCODE
-- SQL_PARAM: PRODNAMEE|text||Filtravimas prekes pavadinima.|operators==,like,in;expr=PRODUCTH.PRODNAMELT
-- SQL_PARAM: TLICSUBTYPE|text||Filtravimas prekes TLICSUBTYPE.|operators==,like,in;expr=VOCPREK.TLICSUBTYPE 
-- SQL_PARAM: FOOD|text||Filtravimas prekes pagal lauka FOOD vedant 1 arba 0.|operators==,like,in;expr=PRODUCT.FOOD 


SELECT 
	own.SHORTNAME as [OWNER]
	,PRODUCTH.[SID]
	,PRODUCT.SALEOUTTERM
	,PRODUCTH.INF_PREK
	,PRODUCT.PRODUCTID
	,PRODUCTH.BARCODE
	,PRODUCTH.PRODNAMELT
	,PRODUCT.FOOD
	,VOCPREK.LogisticProdType
	,VOCPREK.LogisticProdCategory
	,VOCPREK.TLICSUBTYPE 
	,TLICTYPE.ALCO
	,ISNULL(DEPOSITE.DEPOSITE_Y_N,'N') as DEPOSITE_Y_N
	,BRANDH.BRANDNAME
	,GROUPS.GROUP_NAME1
	,GROUPS.GROUP_NAME2
	,GROUPS.GROUP_NAME3
	,GROUPS.GROUP_NAME4
	,GROUPS.GROUP_NAME5
	,PRODUCTH.KORG
	,PRODUCTH.BRUTTO
	,PRODUCTH.KIEKP
	,PRODUCTH.KIEKD
	,PRODUCTH.KIEKM
	,PRODUCTH.ITEMCNT
	,PRODUCTH.DNET
	,PRODUCTH.TLIC
	,PRODUCTH.TNET
	,PRODUCTH.STORTMP1
FROM [QLIKDATA].[dbo].[PRODUCTH] as PRODUCTH WITH (NOLOCK)
LEFT JOIN [SNTXDATA].[dbo].[OWNER] as own WITH (NOLOCK) on own.ID=PRODUCTH.OWNERID and own.FIRMID=PRODUCTH.FIRMID
LEFT JOIN [QLIKBLS].[dbo].[PRODUCTH] as PRODUCTH_BL WITH (NOLOCK) on PRODUCTH_BL.INF_PREK=PRODUCTH.INF_PREK and PRODUCTH_BL.FIRMID='BL'
LEFT JOIN  QLIKDATA.dbo.GROUPS as GROUPS WITH (NOLOCK) on GROUPS.GROUP_ID=CASE WHEN PRODUCTH.[SID]='LOG' and not ISNULL(PRODUCTH_BL.GROUPID,0)=0 THEN PRODUCTH_BL.GROUPID ELSE PRODUCTH.GROUPID	END

LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.PRODUCTID=PRODUCTH.PRODUCTID and VOCPREK.FIRMID=PRODUCTH.FIRMID
LEFT JOIN WM0.SNTXDB.dbo.TLICTYPE as TLICTYPE WITH (NOLOCK) on TLICTYPE.FIRMID = VOCPREK.FIRMID and TLICTYPE.[TYPE] = VOCPREK.TLIC
LEFT JOIN SNTXDATA.dbo.PRODUCT as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID = PRODUCTH.FIRMID and PRODUCT.INF_PREK = PRODUCTH.INF_PREK and PRODUCT.ACTIVE = 1
LEFT JOIN [QLIKDATA].[dbo].[BRANDH]as BRANDH WITH (NOLOCK) on BRANDH.BRANDID=PRODUCTH.BRANDID and BRANDH.ACTIVE=1
LEFT JOIN (SELECT 	
       VOCPREK.[FIRMID]
	  ,VOCPREK.PREKUNI
	  ,'Y' as DEPOSITE_Y_N
  FROM [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK)
  LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as TARA WITH (NOLOCK) on TARA.FIRMID=VOCPREK.FIRMID and TARA.PRODUCTID=VOCPREK.TARAPRODUCTID
  WHERE VOCPREK.FIRMID='SA' and TARA.TLIC in ('X')
) as DEPOSITE on DEPOSITE.PREKUNI=PRODUCTH.INF_PREK 
WHERE 
PRODUCTH.[SID] in ('SNT','LOG','SEE','LVN')
and PRODUCTH.ACTIVE=1 
and not RIGHT(PRODUCTH.INF_PREK,2) in ('ZP','ZR','ZT','ZN','ZK','ZI','ZG','ZA','Z5')
and PRODUCTH.FIRMID = @FIRMID
/* SQL_PARAM_FILTERS */
