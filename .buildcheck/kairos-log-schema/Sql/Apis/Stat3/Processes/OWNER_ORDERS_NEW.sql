-- SQL_DESCRIPTION: Uzsakymo detales pagal savininka, parodo uzsakymus pagal transportavimo diena nuo siandien +1 (be taros!!!)
-- SQL_PARAM_MUST: @OWNER|text||Prekiu savininko kodas. Iveskite tiksliai 3 simbolius, pvz. SNX.|regex=^[A-Za-z0-9]{3}$;message=@OWNER turi buti tiksliai 3 raides arba skaiciai.
-- SQL_PARAM: POSID|text||Filtravimas pagal POSID.|operators==,like,in;expr=ORDSTAT.POSID
-- SQL_PARAM: ORDSTATID|text||Filtravimas pagal ORDSTATID.|operators==,like,in;expr=ORDSTAT.ORDSTATID
-- SQL_PARAM: REFORDERNUM|text||Filtravimas pagal REFORDERNUM.|operators==,like,in;expr=ORDSTAT.REFORDERNUM
-- SQL_PARAM: INVOICENO|text||Filtravimas pagal INVOICENO.|operators==,like,in;expr=INVOICE.INVOICENO

SELECT
		CASE WHEN ORDSTAT.ORDERDEST=2 AND ORDSTAT.VALID=0 AND ORDSTAT.ORDERSTATUS IN (8,9) THEN 'Cancelled in CC'
		 WHEN ORDSTAT.ORDERDEST=2 AND ORDSTAT.VALID=0 THEN 'Transfered to CC'
		 WHEN ((ORDSTAT.ORDERSTATUS=1 and (ISNULL(ORDSTATROW.LINESTATUS,0)=0 or ORDSTATROW.LINESTATUS=9)) or ORDSTAT.ORDERSTATUS=9) or ORDSTATROW.AMOUNT=0 THEN 'NOT SHIPPED (not enough STOCK)'
--		 WHEN (ORDSTAT.ORDERSTATUS=1 and (LEN(VAZTAR.NKRO)>1 or LEN(VAZTAR.NSAD)>0 or not INVOICE.INVOICENO is NULL)) and (not RECEIPTCONFIRMATION.ISSUEDATETIME is NULL) THEN 'Departed'
		 WHEN (ORDSTAT.ORDERSTATUS=1 and (LEN(VAZTAR.NKRO)>1 or LEN(VAZTAR.NSAD)>0 or not INVOICE.INVOICENO is NULL)) THEN 'Ready to dispatch'
		 WHEN (ORDSTAT.ORDERSTATUS=1 and LEN(ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO))>1 and ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)=0) or ORDSTATROW.AMOUNT=0 THEN 'NOT SHIPPED'
		 WHEN ORDSTAT.ORDERSTATUS=1 and LEN(ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO))>1 and not ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)>0 THEN 'Picked waiting document'
		 WHEN ORDSTAT.ORDERSTATUS=1 and ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)>0 THEN 'Picked waiting document' --'Shipped'
		 WHEN not ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO) is NULL THEN 'Picking'
		 WHEN ISNULL(ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO),0)=0 THEN 'Suspend in PREKES'
	 ELSE 'Picking' 
	 END as ORDSTATUS
	 ,CASE  WHEN ((ORDSTAT.ORDERSTATUS=1 and (ISNULL(ORDSTATROW.LINESTATUS,0)=0 or ORDSTATROW.LINESTATUS=9)) or ORDSTAT.ORDERSTATUS=9) or ORDSTATROW.AMOUNT=0 THEN NULL
		 WHEN (ORDSTAT.ORDERSTATUS=1 and LEN(ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO))>1 and ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)=0) or ORDSTATROW.AMOUNT=0 THEN NULL
		 WHEN not INVOICE.INVOICEDATE is NULL THEN DATEDIFF(day, ORDSTATTRP.DVAZNEW,ISNULL(INVOICE.INVOICEDATE,GETDATE()))
	 ELSE NULL
	 END as DVAZ_DIFF 
	 ,INVOICE.OPERTYPE
	 ,INVOICE.SUBOPERTYPE
	 ,INVOICE.DOCTYPE
	,ORDSTATTRP.DVAZNEW
	,ORDSTATTRP.TRPGROUP
	,INVOICE.INVOICEDATE
	,INVOICE.ADDTIME as INVOICE_TIME 
	,INVOICE.CARNUMBER
	,ORDSTAT.XMLORDHEADNW 
	,ORGALL.COUNTRY
	,ORDSTAT.ORDSOURCE 
	,ORDSTAT.ORDSENDERID
	,ORDSTAT.ORDSENDERID as SENDERID 
    ,ORDSTAT.ORDSTATID
	,ORDSTAT.REFORDERNUM
	,ORDSTAT.ORDERTYPE
	,ORDSTAT.DATEBEGIN as ORDER_DATEBEGIN
	,ORDSTAT.SENDTIME as ORDER_SENDTIME
	,[OWNER].SHORTNAME as [OWNER]
	,ORGPOS.SALETYPE
	,ORDSTAT.POSID
	,ORGALL.ONAME
	,ORGPOS.[ADDRESS]
	,ORDSTATROW.PREFSTOCK
	,ORDSTATROW.LINESTATUS 
	,PCKORDERNO = ISNULL(ORDSTATROW.PICKINGTASKID,ORDSTATROW.PCKORDERNO)
	,ORDSTATROW.PRODUCTID
	,VOCPREK.INF_PREK
	,VOCPREK.TLIC
	,VOCPREK.INF_PAVADL
	,ORDSTATROW.AMOUNTORIG
	,ORDSTATROW.AMOUNT
	,ORDSTATROW.AMOUNTSHIPPED
	,INVOICE.INVOICEID
	,INVOICE.INVOICENO
	,INVOICELINE.VALIDUNTIL
	,INVOICELINE.QUANTITY
	,BRUTTO = CASE
		WHEN VOCPREK.BRUTTO>0 THEN VOCPREK.BRUTTO
		ELSE VOCPREK.NETTO
	END
	 ,[BRUTTO_KG_ORDERED] = CASE
		 WHEN VOCPREK.TVNT='K' and VOCPREK.TLIC!='D' THEN ORDSTATROW.AMOUNTORIG/VOCPREK.DNET * VOCPREK.BRUTTO
		 WHEN VOCPREK.TLIC!='D' THEN ORDSTATROW.AMOUNTORIG * VOCPREK.BRUTTO
		 ELSE '0'
	 END
	 ,[BRUTTO_KG_SHIPED] = CASE
	 	 WHEN ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)=0 THEN '0'
		 WHEN VOCPREK.TVNT='K' and VOCPREK.TLIC!='D' THEN ORDSTATROW.AMOUNTSHIPPED/VOCPREK.DNET * VOCPREK.BRUTTO
		 WHEN VOCPREK.TLIC!='D' THEN ORDSTATROW.AMOUNTSHIPPED * VOCPREK.BRUTTO
		 ELSE '0'
	  END
	  ,PLL_BY_ORDER= CASE 
	  	WHEN VOCPREK.TLIC='D' THEN '0'
	  	WHEN VOCPREK.TVNT='V' THEN ORDSTATROW.AMOUNTORIG / (VOCPREK.KIEKD * VOCPREK.KIEKP)
		ELSE ORDSTATROW.AMOUNTORIG / VOCPREK.DNET / VOCPREK.KIEKD / VOCPREK.KIEKP
	  END
	  ,PLL_BY_SHIPED= CASE 
	  	WHEN ISNULL(ORDSTATROW.AMOUNTSHIPPED,0)=0 THEN '0'
	  	WHEN VOCPREK.TLIC='D' THEN '0'
	  	WHEN VOCPREK.TVNT='V' THEN ORDSTATROW.AMOUNTSHIPPED / (VOCPREK.KIEKD * VOCPREK.KIEKP)
		ELSE ORDSTATROW.AMOUNTSHIPPED / VOCPREK.DNET / VOCPREK.KIEKD / VOCPREK.KIEKP
	  END
FROM SNTXDATA.dbo.ORDSTAT as ORDSTAT WITH (NOLOCK)
LEFT JOIN SNTXDATA.dbo.[OWNER] as [OWNER] WITH (NOLOCK) on [OWNER].ID=ORDSTAT.OWNERID and [OWNER].FIRMID=ORDSTAT.FIRMID
LEFT JOIN SNTXDATA.dbo.ORGPOS as ORGPOS WITH (NOLOCK) on ORGPOS.POSID=ORDSTAT.POSID and ORGPOS.ACTIVE=1
LEFT JOIN SNTXDATA.dbo.ORGALL as ORGALL WITH (NOLOCK) on ORGALL.ORGID= ORGPOS.ORGID and ORGALL.FIRMID=ORDSTAT.FIRMID
LEFT JOIN SNTXDATA.dbo.ORDSTATROW as ORDSTATROW WITH (NOLOCK) on ORDSTATROW.ORDSTATID=ORDSTAT.ORDSTATID and ORDSTATROW.FIRMID=ORDSTAT.FIRMID
LEFT JOIN SNTXDATA.dbo.VOCPREK as VOCPREK WITH (NOLOCK) on VOCPREK.PRODUCTID=ORDSTATROW.PRODUCTID and VOCPREK.FIRMID=ORDSTATROW.FIRMID
LEFT JOIN [SNTXDATA].[dbo].[ORDSTATTRP] as ORDSTATTRP WITH (NOLOCK) on ORDSTATTRP.ORDSTATID=ORDSTATROW.ORDSTATID and ORDSTATTRP.TRPGROUP=ORDSTATROW.TRPGROUP
LEFT JOIN SNTXDATA.dbo.DATVAZ  as DATVAZ WITH (NOLOCK) on DATVAZ.ORDSTATID=ORDSTATROW.ORDSTATID and DATVAZ.INF_PREK=ORDSTATROW.INF_PREK_X and DATVAZ.FIRMID=ORDSTATROW.FIRMID
LEFT JOIN SNTXDATA.dbo.V_VAZTAR as VAZTAR WITH (NOLOCK) on VAZTAR.NW=DATVAZ.NW and VAZTAR.FIRMID=DATVAZ.FIRMID and VAZTAR.PREFSTOCK=ORDSTATROW.PREFSTOCK
LEFT JOIN SNTXDATA.dbo.INVOICELINE as INVOICELINE WITH (NOLOCK) on INVOICELINE.ORDSTATID=ORDSTATROW.ORDSTATID and INVOICELINE.PRODUCTID=ORDSTATROW.PRODUCTID 
LEFT JOIN SNTXDATA.dbo.INVOICE as INVOICE WITH (NOLOCK) on INVOICE.INVOICEID=INVOICELINE.INVOICEID and INVOICE.FIRMID=ORDSTAT.FIRMID and INVOICE.TEST=0  and not INVOICE.VAZTTYPEID in (24,25,86)
WHERE 
ORDSTATTRP.DVAZNEW>CONVERT(date, GETDATE())
and not VOCPREK.TLIC in ('D','Z')
and ISNULL(INVOICE.CANCELLED,0)=0
and [OWNER].SHORTNAME = @OWNER
/* SQL_PARAM_FILTERS */
ORDER BY ORDSTATTRP.DVAZNEW,ORDSTAT.REFORDERNUM;