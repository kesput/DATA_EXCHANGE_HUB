-- SQL_DESCRIPTION: ECO ir NSP  prekiu gavimas, pakavimas ir supakuoto kiekio lokacija kur nugabentas produktas.
-- SQL_PARAM_MUST: @DATE|date||Pajamavimo data. Pasirinkta data i STAT3 uzklausa perduodama YYYY-MM-DD formatu.|format=yyyy-MM-dd

--DECLARE @DATE date
--SET @DATE = DATEADD(DAY, CASE WHEN DATEDIFF(DAY, '19000101', CAST(GETDATE() AS DATE)) % 7 = 0 THEN -3 ELSE -1 END, CAST(GETDATE() AS DATE));

SELECT   
	  CONVERT(VARCHAR, WO.[ACTION_DATE], 112) as NDATE
	  ,WO.COMPANY AS [OWNER]
	  ,WO.ITEM_DEPARTMENT as KORG
	  ,WO.[REFERENCE_ID]
	  ,WO.LPN as LPN_COME_IN_REPACK
	  ,WO.QUANTITY
	  ,CONVERT(VARCHAR, RFP.[ACTION_DATE], 112)  as PACKED_NDATE
	  ,CONVERT(VARCHAR, FT.[ACTION_DATE], 112) as FORKLIFT_NDATE
	  ,LEFT(WO.ERP_WHS,2) as PREF
	  ,FT.TO_LOC as [LOCATION]
	  ,FT.LPN
	  ,FT.LOT
	  ,FT.ITEM
	  ,VOCPREK.TLICSUBTYPE
	  ,PRODUCT.PRODNAME
	  ,FT.WORKER_NAME

FROM [BLSTXSTA3].[ILSLT].[dbo].[BLS_MANH_OPERATIONS_CURRENT] as WO WITH (NOLOCK) 
LEFT JOIN [BLSTXSTA3].[ILSLT].[dbo].[BLS_MANH_OPERATIONS_CURRENT] as RFP WITH (NOLOCK) on RFP.WORK_A = 'Packing' and RFP.WORK_B = 'Receiving from pack' and RFP.[REFERENCE_ID] = WO.[REFERENCE_ID] and RFP.ITEM = WO.ITEM and RFP.LPN=WO.LPN_TO
LEFT JOIN [BLSTXSTA3].[ILSLT].[dbo].[BLS_MANH_OPERATIONS_CURRENT] as FT WITH (NOLOCK) on FT.WORK_A = 'Packing' and FT.WORK_B = 'Forklift Transfer' and FT.[REFERENCE_ID] = RFP.[REFERENCE_ID] and FT.ITEM = RFP.ITEM and FT.LPN = RFP.LPN
LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID = 'SA' and PRODUCT.INF_PREK = WO.ITEM and PRODUCT.ACTIVE = 1
LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.FIRMID = 'SA' and VOCPREK.INF_PREK = WO.ITEM
WHERE 
    (CAST(WO.[ACTION_DATE] as date) = @DATE
	or CAST(RFP.[ACTION_DATE] as date) = @DATE
	or CAST(FT.[ACTION_DATE] as date) = @DATE)
	AND WO.WORK_A ='Packing'
	AND WO.WORK_B ='Work order'
	AND (
        VOCPREK.TLICSUBTYPE='ECO' 
        OR PRODUCT.PRODNAME LIKE '%EKO-%' 
        OR PRODUCT.PRODNAME LIKE '%ekolog%'
        OR PRODUCT.PRODNAME LIKE '% organic%' 
        OR (PRODUCT.PRODNAME LIKE '% org%' AND PRODUCT.PRODNAME NOT LIKE '% orginal%' AND PRODUCT.PRODNAME NOT LIKE '%vidaus org%') 
		OR WO.ITEM_DEPARTMENT='NSP'
    )
ORDER BY WO.ITEM,WO.[WORK_B]