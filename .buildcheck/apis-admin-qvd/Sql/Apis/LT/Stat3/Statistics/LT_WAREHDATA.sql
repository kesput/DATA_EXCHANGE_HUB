-- SQL_PARAM_MUST: @OWNER|text||Prekiu savininko kodas. Iveskite tiksliai 3 simbolius, pvz. SNX.|regex=^[A-Za-z0-9]{3}$;message=@OWNER turi buti tiksliai 3 raides arba skaiciai.
-- SQL_PARAM_MUST: @SNDATE|date||Laikotarpio pradzios data i STAT3 uzklausa perduodama YYYYMMDD formatu.|format=yyyyMMdd
-- SQL_PARAM_MUST: @ENDATE|date||Laikotarpio pabaigos data i STAT3 uzklausa perduodama YYYYMMDD formatu.|format=yyyyMMdd
SELECT 
	   [OWNER].SHORTNAME as [OWNER]
	  ,[WAREHDATA].[NDATE]
      ,[WAREHDATA].[FIRMID]
      ,[WAREHDATA].[DATASOURCE]
      ,[WAREHDATA].[WRHCODE]
      ,[WAREHDATA].[ZONENAME]
      ,[WAREHDATA].[PALETID]
      ,[WAREHDATA].[PRODUCTCODE]
      ,[WAREHDATA].[PRODUCTID]
      ,[WAREHDATA].[WSTATUS]
      ,[WAREHDATA].[PREFSTOCK]
      ,[WAREHDATA].[PALETCOUNT]
      ,[WAREHDATA].[FLOORNUM]
      ,[WAREHDATA].[ZONETYPE]
      ,[WAREHDATA].[ZONESTATUS]
      ,[WAREHDATA].[DATERECV]
      ,[WAREHDATA].[VALIDUNTIL]
      ,[WAREHDATA].[STOCK]
      ,[WAREHDATA].[BOXCNT]
      ,[WAREHDATA].[ADDTIME]
      ,[WAREHDATA].[PALETWIDTHCOEF]
      ,[WAREHDATA].[ZONESUBTYPE]
      ,[WAREHDATA].[CONTAINERTYPE]
      ,[WAREHDATA].[ZONEUSAGE]
      ,[WAREHDATA].[LPN_VOLUME]
      ,[WAREHDATA].[LPN_WEIGHT]
      ,[WAREHDATA].[LOT]
      ,[WAREHDATA].[SSCC]
      ,[WAREHDATA].[DATESTAMP]
      ,[WAREHDATA].[ALLOCATION_ZONE]
      ,[WAREHDATA].[LOCATING_ZONE]
      ,[WAREHDATA].[WORK_ZONE]
      ,[WAREHDATA].[RACK_TYPE]
      ,[WAREHDATA].[HISTORY_FROM]
      ,[WAREHDATA].[ZONEHEIGHT]
      ,[PALETHEIGHT]
      ,[WAREHDATA].[ZONELENGHT]
      ,[WAREHDATA].[ZONEWIDTH]
      ,[WAREHDATA].[ZONEVOLUME]
      ,[WAREHDATA].[WAREHOUSETYPE]
      ,[WAREHDATA].[WAREHOUSEZONE]
      ,[WAREHDATA].[TAXTYPE]
      ,[WAREHDATA].[PRODUCTCATEGORY]
      ,[WAREHDATA].[WAREHDATAID]
  FROM [SNTXDATA].[dbo].[WAREHDATA]  as [WAREHDATA]
  LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.INF_PREK=[WAREHDATA].PRODUCTCODE  and PRODUCT.FIRMID=[WAREHDATA].FIRMID 
  LEFT JOIN SNTXDATA.dbo.[OWNER] AS [OWNER] WITH (NOLOCK) ON [OWNER].ID = PRODUCT.OWNERID
  WHERE [WAREHDATA].FIRMID='SA'
  and [OWNER].SHORTNAME=@OWNER
  and ([WAREHDATA].NDATE>=@SNDATE or [WAREHDATA].NDATE=@ENDATE)