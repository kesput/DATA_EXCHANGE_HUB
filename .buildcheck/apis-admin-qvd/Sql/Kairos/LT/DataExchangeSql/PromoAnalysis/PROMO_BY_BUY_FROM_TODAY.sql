-- SQL_DESCRIPTION: PROMO FORECAST planuojamas pirkimas nuo siandienos pagal BUY_START.
-- SQL_FILTER: CLIENT|KAIROS_PROMO_FORECAST.[CLIENT]|text|eq,like,in|Klientas / tinklas.
-- SQL_FILTER: INF_PREK|KAIROS_PROMO_FORECAST.[INF_PREK]|text|eq,like,in|Vidinis prekes kodas.
-- SQL_FILTER: PROMO_START|KAIROS_PROMO_FORECAST.[PROMO_START]|date|eq,gte,lte|Akcijos pradzios data.
-- SQL_FILTER: PROMO_END|KAIROS_PROMO_FORECAST.[PROMO_END]|date|eq,gte,lte|Akcijos pabaigos data.
-- SQL_FILTER: STATUS|KAIROS_PROMO_FORECAST.[STATUS]|text|eq,like,in|PROMO FORECAST statusas.

SELECT
      KAIROS_PROMO_FORECAST.[CLIENT]
      ,KAIROS_PROMO_FORECAST.[INF_PREK]
      ,KAIROS_PROMO_FORECAST.[BUY_START]
      ,KAIROS_PROMO_FORECAST.[PROMO_START]
      ,KAIROS_PROMO_FORECAST.[PROMO_END]
      ,KAIROS_PROMO_FORECAST.[QTY] AS PLAN_PROMO_QTY
      ,KAIROS_PROMO_FORECAST.[INFO_DATE]
      ,KAIROS_PROMO_FORECAST.[STATUS]
FROM [BLS_LOGIT_STAT].[dbo].[KAIROS_PROMO_FORECAST] AS KAIROS_PROMO_FORECAST WITH (NOLOCK)
WHERE KAIROS_PROMO_FORECAST.[BUY_START] >= CAST(GETDATE() AS date)
/* SQL_PARAM_FILTERS */
ORDER BY
      KAIROS_PROMO_FORECAST.[BUY_START]
      ,KAIROS_PROMO_FORECAST.[CLIENT]
      ,KAIROS_PROMO_FORECAST.[INF_PREK];
