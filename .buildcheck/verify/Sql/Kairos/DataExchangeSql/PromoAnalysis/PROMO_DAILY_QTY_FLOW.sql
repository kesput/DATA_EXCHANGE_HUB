-- SQL_DESCRIPTION: PROMO FORECAST ateinanciu dienu srautas pagal BUY_START su totaliniu QTY kiekiu.
-- SQL_FILTER: BUY_START|KAIROS_PROMO_FORECAST.[BUY_START]|date|eq,gte,lte|Kliento pirkimo pradzios data.
-- SQL_FILTER: CLIENT|KAIROS_PROMO_FORECAST.[CLIENT]|text|eq,like,in|Klientas / tinklas.
-- SQL_FILTER: INF_PREK|KAIROS_PROMO_FORECAST.[INF_PREK]|text|eq,like,in|Vidinis prekes kodas.
-- SQL_FILTER: STATUS|KAIROS_PROMO_FORECAST.[STATUS]|text|eq,like,in|PROMO FORECAST statusas.

SELECT
      CAST(KAIROS_PROMO_FORECAST.[BUY_START] AS date) AS BUY_START
      ,COUNT_BIG(1) AS PROMO_LINES
      ,COUNT(DISTINCT KAIROS_PROMO_FORECAST.[CLIENT]) AS CLIENTS_COUNT
      ,COUNT(DISTINCT KAIROS_PROMO_FORECAST.[INF_PREK]) AS PRODUCTS_COUNT
      ,SUM(ISNULL(KAIROS_PROMO_FORECAST.[QTY], 0)) AS TOTAL_QTY
FROM [BLS_LOGIT_STAT].[dbo].[KAIROS_PROMO_FORECAST] AS KAIROS_PROMO_FORECAST WITH (NOLOCK)
WHERE KAIROS_PROMO_FORECAST.[BUY_START] >= CAST(GETDATE() AS date)
/* SQL_PARAM_FILTERS */
GROUP BY
      CAST(KAIROS_PROMO_FORECAST.[BUY_START] AS date)
ORDER BY
      BUY_START;
