-- SQL_DESCRIPTION: ECO prekiu pakavimo detales pagal parinkta diena
-- SQL_PARAM_MUST: @SNDATE|date||Pradzios data|format=yyyyMMdd
-- SQL_PARAM_MUST: @ENDATE|date||Pabaigos data|format=yyyyMMdd


SELECT   
	 DATVAZ.NDORD  
	 ,CONVERT(varchar, DATEADD(s, ISNULL(DATEDIFF(s, CAST(VAZTAR.INVOICECREATETIME AS date), VAZTAR.INVOICECREATETIME), VAZTAR.TIMO), ''), 108) as TIME 
	 ,DATVAZ.PREFSTOCK as ERP
	 ,VAZTAR.RELPREFSTOCK as ERP_FROM
	 ,DOCUMENT = CASE   
					 WHEN RTRIM(VAZTAR.NSAD) != '' THEN RTRIM(VAZTAR.NSAD)  
					 WHEN VAZTAR2.NW IS NOT NULL THEN RTRIM(VAZTAR2.NSAD)  
					 WHEN RTRIM(VAZTAR.NKRO) != '' THEN RTRIM(VAZTAR.NKRO)  
					 WHEN VAZTAR2.NW IS NOT NULL THEN RTRIM(VAZTAR2.NKRO) 
					 ELSE '' END  
	 ,ECO_ALCO = CASE  
					WHEN VOCPREK.TLICSUBTYPE='ECO' and TLICTYPE.ALCO=1 THEN 'ECO/ALCO'
					WHEN VOCPREK.TLICSUBTYPE='ECO' THEN 'ECO'
					WHEN TLICTYPE.ALCO=1 THEN 'ALCO'
				 ELSE '' END 
	 ,[OWNER].SHORTNAME as [OWNER]
	 ,SUPPLIER.CODE as KORG 
	 ,SUPPLIER.[NAME] as SUPPLIER_NAME 
	 ,DATVAZ.INF_PREK 
	 ,PRODUCTSREL.ToInf_Prek as INF_PREK_MAPED
	 ,PRODUCT.PRODNAME 
	 ,ABS(DATVAZ.AMOUNT) as AMOUNT 

 FROM [SNTXDATA].[dbo].[DATVAZ] as DATVAZ WITH (NOLOCK) 
 LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.FIRMID=DATVAZ.FIRMID and VOCPREK.INF_PREK=DATVAZ.INF_PREK 
 LEFT JOIN [WM0].[SNTXDB].[dbo].[TLICTYPE] as TLICTYPE WITH (NOLOCK) on TLICTYPE.FIRMID=VOCPREK.FIRMID and TLICTYPE.[TYPE]=VOCPREK.TLIC 
 LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID=DATVAZ.FIRMID and PRODUCT.INF_PREK=DATVAZ.INF_PREK 
 LEFT JOIN [WM0].[SNTXDB].[dbo].[PRODUCTSREL] as PRODUCTSREL WITH (NOLOCK) on PRODUCTSREL.FIRMID = PRODUCT.FIRMID and PRODUCTSREL.FromInf_Prek = PRODUCT.INF_PREK --and PRODUCTSREL.ACTIVE=1
 LEFT JOIN [SNTXDATA].[dbo].[OWNER] as [OWNER] WITH (NOLOCK) on [OWNER].ID=PRODUCT.OWNERID and [OWNER].FIRMID=DATVAZ.FIRMID 
 LEFT JOIN [SNTXDATA].[dbo].[SUPPLIER] as SUPPLIER WITH (NOLOCK) on SUPPLIER.FIRMID=DATVAZ.FIRMID and SUPPLIER.CODE=PRODUCT.KORG 
 LEFT JOIN [SNTXDATA].[dbo].[VAZTAR] as VAZTAR WITH (NOLOCK) on VAZTAR.FIRMID = DATVAZ.FIRMID AND VAZTAR.PREFSTOCK = DATVAZ.PREFSTOCK AND VAZTAR.NW = DATVAZ.NW 
 LEFT JOIN [SNTXDATA].[dbo].[VAZTAR] as VAZTAR2 WITH (NOLOCK) on VAZTAR2.FIRMID = VAZTAR.FIRMID AND VAZTAR2.PREFSTOCK = VAZTAR.PREFSTOCK AND VAZTAR2.NW = VAZTAR.NWMA 
 LEFT JOIN [SNTXDATA].[dbo].[DATVAZPROP] as DATVAZPROP WITH (NOLOCK) on DATVAZPROP.NDORD=DATVAZ.NDORD and DATVAZPROP.FIRMID=DATVAZ.FIRMID and DATVAZPROP.NW=DATVAZ.NW and DATVAZPROP.NUM=DATVAZ.NUM and DATVAZPROP.PREFSTOCK=DATVAZ.PREFSTOCK 
 LEFT LOOP JOIN [SNTXDATA].dbo.VOCORG AS VOCORG WITH (NOLOCK) ON VOCORG.CODEORG = VAZTAR.CORG AND VOCORG.PREF = DATVAZ.[PREF] AND VOCORG.FIRMID = DATVAZ.FIRMID 
 LEFT LOOP JOIN [SNTXDATA].dbo.ORGPOS AS ORGPOS WITH (NOLOCK) ON ORGPOS.POSID = VOCORG.POSID 
 WHERE DATVAZ.FIRMID='SA' 
 and ((DATVAZ.AMOUNT < 0) and VAZTAR.CANC = 'N' and VAZTAR.VTYP <> 'C' and VAZTAR.TPER in ('V','P','D')) 
 and DATVAZ.[PREF]='VBL'
 and (
	 VOCPREK.TLICSUBTYPE='ECO' 
	 or PRODUCT.PRODNAME like '%EKO-%' 
	 or PRODUCT.PRODNAME like '%ekolog%'
	 or PRODUCT.PRODNAME like '% organic%' 
	 or (PRODUCT.PRODNAME like '% org%' and not PRODUCT.PRODNAME like '% orginal%' and not PRODUCT.PRODNAME like '%vidaus org%')
	 )
 and (
		(RIGHT(DATVAZ.PREFSTOCK,1) in ('1','2','5','7','K') and RIGHT(VAZTAR.RELPREFSTOCK,1) in ('B','F','G','4'))
		)
 and DATVAZ.NDORD>=@SNDATE
 and DATVAZ.NDORD<=@ENDATE 
 and LEFT(DATVAZ.INF_PREK,3)!='BEL'


UNION

SELECT 
	  INVOICE.NDATE as NDORD
	  ,CONVERT(varchar, INVOICE.CREATEDTIME, 108) as TIME 
	 ,INVOICELINE_IN.PICKPREFSTOCK as ERP
	 ,INVOICE.INVPREFSTOCK as ERP_FROM
	 ,INVOICE.INVOICENO as DOCUMENT
	 ,ECO_ALCO = CASE  
					WHEN VOCPREK.TLICSUBTYPE='ECO' and TLICTYPE.ALCO=1 THEN 'ECO/ALCO'
					WHEN VOCPREK.TLICSUBTYPE='ECO' THEN 'ECO'
					WHEN TLICTYPE.ALCO=1 THEN 'ALCO'
				 ELSE '' END 
	 ,[OWNER].SHORTNAME as [OWNER]
	 ,SUPPLIER.CODE as KORG 
	 ,SUPPLIER.[NAME] as SUPPLIER_NAME 
	 ,INVOICELINE_IN.INF_PREK
	 ,PRODUCTSREL.ToInf_Prek as INF_PREK_MAPED
	 ,PRODUCT.PRODNAME 
	 ,INVOICELINE_IN.QUANTITY as AMOUNT
FROM [SNTXDATA].[dbo].[INVOICE] as INVOICE WITH (NOLOCK) 
	 LEFT JOIN [SNTXDATA].[dbo].[INVOICELINE] as INVOICELINE_IN WITH (NOLOCK) on INVOICELINE_IN.INVOICEID=INVOICE.INVOICEID and INVOICELINE_IN.OUTPUTRECLASSIFICATION='No'
	 LEFT JOIN [SNTXDATA].[dbo].[VOCPREK] as VOCPREK WITH (NOLOCK) on VOCPREK.FIRMID=INVOICE.FIRMID and VOCPREK.INF_PREK=INVOICELINE_IN.INF_PREK 
	 LEFT JOIN [WM0].[SNTXDB].[dbo].[TLICTYPE] as TLICTYPE WITH (NOLOCK) on TLICTYPE.FIRMID=VOCPREK.FIRMID and TLICTYPE.[TYPE]=VOCPREK.TLIC 
	 LEFT JOIN [SNTXDATA].[dbo].[PRODUCT] as PRODUCT WITH (NOLOCK) on PRODUCT.FIRMID=INVOICE.FIRMID and PRODUCT.INF_PREK=INVOICELINE_IN.INF_PREK 
	 LEFT JOIN [WM0].[SNTXDB].[dbo].[PRODUCTSREL] as PRODUCTSREL WITH (NOLOCK) on PRODUCTSREL.FIRMID = PRODUCT.FIRMID and PRODUCTSREL.FromInf_Prek = PRODUCT.INF_PREK
	 LEFT JOIN [SNTXDATA].[dbo].[OWNER] as [OWNER] WITH (NOLOCK) on [OWNER].ID=PRODUCT.OWNERID and [OWNER].FIRMID=INVOICE.FIRMID 
	 LEFT JOIN [SNTXDATA].[dbo].[SUPPLIER] as SUPPLIER WITH (NOLOCK) on SUPPLIER.FIRMID=INVOICE.FIRMID and SUPPLIER.CODE=PRODUCT.KORG 
	 LEFT JOIN [SNTXDATA].[dbo].[PREFDESC] as PREFDESC WITH (NOLOCK) on PREFDESC.ACTIVE=1 and PREFDESC.FIRMID=INVOICE.FIRMID and PREFDESC.PREFSTOCK=LEFT(INVOICELINE_IN.PICKPREFSTOCK,2)
 WHERE 
	 INVOICE.OPERTYPE='Reclassification'
	 and INVOICE.ACTIVE=1
	 and INVOICE.TEST=0
	 and LEFT(INVOICELINE_IN.INF_PREK,3)!='BEL'
	 and (
	 VOCPREK.TLICSUBTYPE='ECO' 
	 or PRODUCT.PRODNAME like '%EKO-%' 
	 or PRODUCT.PRODNAME like '%ekolog%'
	 or PRODUCT.PRODNAME like '% organic%' 
	 or (PRODUCT.PRODNAME like '% org%' and not PRODUCT.PRODNAME like '% orginal%' and not PRODUCT.PRODNAME like '%vidaus org%')
	 )
	 and INVOICE.NDATE>=@SNDATE
	 and INVOICE.NDATE<=@ENDATE
	 and PREFDESC.PREF='VBM'