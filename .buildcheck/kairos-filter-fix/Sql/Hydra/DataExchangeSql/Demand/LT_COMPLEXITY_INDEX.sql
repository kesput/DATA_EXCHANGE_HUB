-- HYDRA_FILTER: YYYYMM_FROM | ci.YYYYMM_FROM | int | =,>=,<=,in,!=
-- HYDRA_FILTER: YYYYMM_TILL | ci.YYYYMM_TILL | text | =,like,in,!=
-- HYDRA_FILTER: INF_PREK | ci.INF_PREK | text | =,like,in,!=
-- HYDRA_FILTER: COMPLEXITY_INDEX | ci.COMPLEXITY_INDEX | decimal | =,>=,<=,in,!=

SELECT
    ci.YYYYMM_FROM,
    ci.YYYYMM_TILL,
    ci.INF_PREK,
    PRODUCTH.PRODNAMELT,
    ci.COMPLEXITY_INDEX,
    ci.COMPLEXITY_REASON,
    ci.IS_ACTIVE,
    ci.UPDATED_AT,
    ci.UPDATED_BY
FROM [BLS_LOGIT_STAT].[dbo].[HYDRA_COMPLEXITY_INDEX] AS ci
LEFT JOIN [SQL-SQLSTA3-PRD].[QLIKDATA].[dbo].[PRODUCTH] AS PRODUCTH
    ON PRODUCTH.INF_PREK = ci.INF_PREK
   AND PRODUCTH.ACTIVE = 1
   AND PRODUCTH.[SID] IN ('SNT', 'LOG')
   AND PRODUCTH.FIRMID='SA'
WHERE 1=1
